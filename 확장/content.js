// ── 방이 생기기 전 대화를 옮겨 담기 ─────────────────────────────
// 프로젝트 대화에 방이 막 생겼을 때, 화면에 이미 있는 내 말과 GPT 답을 최근 것부터
// 대화가져오기최대 개까지 순서대로 남긴다. 지문을 붙여 보내므로 서버가 겹침을 거른다.
// 바구니가 든 답, 소쿠리·재촉·예약 같은 에이전트 글은 옮기지 않는다.
const 대화가져오기최대 = 20;

// ChatGPT가 같은 메시지를 화면에 두 번 그릴 때가 있다(메시지 번호가 같다). 한 번만 센다.
function 메시지겹침빼기(목록) {
  const 본 = new Set();
  return 목록.filter((el) => {
    const 번호 = 메시지번호(el);
    if (!번호) return true;
    if (본.has(번호)) return false;
    본.add(번호);
    return true;
  });
}

function 화면순서로(사람들, 답들) {
  사람들 = 메시지겹침빼기(사람들);
  답들 = 메시지겹침빼기(답들);
  const 모두 = 사람들.map((el) => ({ el, 누구: '사용자' }))
    .concat(답들.map((el) => ({ el, 누구: 'gpt' })));
  const 앞뒤 = 모두[0] && 모두[0].el && typeof 모두[0].el.compareDocumentPosition === 'function';
  if (앞뒤) {
    모두.sort((가, 나) => (가.el.compareDocumentPosition(나.el) & 4 ? -1 : 1));
    return 모두;
  }
  // 위치를 못 재면 '내 말 → 답' 이 번갈아 온다고 본다
  const 섞음 = [];
  for (let i = 0; i < Math.max(사람들.length, 답들.length); i++) {
    if (사람들[i]) 섞음.push({ el: 사람들[i], 누구: '사용자' });
    if (답들[i]) 섞음.push({ el: 답들[i], 누구: 'gpt' });
  }
  return 섞음;
}

async function 화면대화가져오기(방) {
  const 목록 = 화면순서로(모두찾기(셀렉터.사용자메시지), 모두찾기(셀렉터.어시스턴트메시지))
    .slice(-대화가져오기최대);
  let 옮김 = 0;
  for (const { el, 누구 } of 목록) {
    if (상태.지금방 !== 방) return 옮김;          // 그사이 다른 대화로 갔다
    const 원문 = 화면읽기글뺌(String(el.innerText || el.textContent || '').trim());
    if (!원문) continue;
    if (누구 === '사용자') {
      if (사람말아닌가(원문)) continue;
      const 열쇠 = 답변아이디(el, '글' + 지문(원문));
      if (상태.남긴내말.has(열쇠)) continue;
      await 대화남기기('사용자', 원문, 'u:' + 열쇠);
      상태.남긴내말.add(열쇠);
    } else {
      if (원문.indexOf(규약.요청시작) !== -1) continue;
      let 보일글 = '';
      try { 보일글 = 답을마크다운으로(el); } catch (e) { /* 화면 글 그대로 */ }
      await 대화남기기('gpt', 보일글 || 원문, 지문(원문));
      상태.마지막기록텍스트 = 원문;
    }
    옮김 += 1;
  }
  if (옮김) await 내말기록남기기();
  return 옮김;
}

// ── 사람이 ChatGPT에 직접 쓴 말 ──────────────────────────────
// 마지막 내 말 하나만 본다. 옛말을 훑으면 대화를 열 때마다 옛말이 기록 끝에 쏟아진다.
// 처음 여는 대화는 잠깐(내말기준ms) 화면에 있던 말을 '이미 본 것' 으로만 친다.
// 결과(소쿠리)와 자동 재촉은 사람 말이 아니라 안 남긴다.

const 내말기준ms = 3000;
const 내말기록최대 = 50;

function 내말기록열쇠(번호) {
  return '내말기록:' + 번호;
}

async function 내말기록불러오기(번호) {
  상태.남긴내말 = new Set();
  상태.내말기록있음 = false;
  상태.내말기준때 = Date.now();
  if (!번호 || !chrome.storage || !chrome.storage.local) return;
  try {
    const 열쇠 = 내말기록열쇠(번호);
    const 받은것 = await chrome.storage.local.get(열쇠);
    const 기록 = 받은것 && 받은것[열쇠];
    if (!기록) return;
    상태.남긴내말 = new Set(기록.열쇠들 || []);
    상태.내말기록있음 = true;
  } catch (e) { /* 저장소를 못 읽으면 메모리로만 */ }
}

async function 내말기록남기기() {
  const 번호 = 상태.대화번호;
  상태.내말기록있음 = true;
  if (!번호 || !chrome.storage || !chrome.storage.local) return;
  try {
    await chrome.storage.local.set({
      [내말기록열쇠(번호)]: { 열쇠들: Array.from(상태.남긴내말).slice(-내말기록최대), 때: Date.now() },
    });
  } catch (e) { /* 넘어간다 */ }
}

function 사람말아닌가(글) {
  if (글.indexOf(규약.응답시작) !== -1 && 글.indexOf(규약.응답끝) !== -1) return true;
  if (글.indexOf(예약머리) === 0) return true;      // 예약 알림은 판에 ⏰ 로 따로 남긴다
  if (글.indexOf(설치결과머리) === 0) return true;
  return 글 === 재촉글;
}

const 설치결과머리 = '【설치 허용 결과】';

// ChatGPT가 paste 이벤트를 화면에만 그려 놓고 내부 편집기에는 반영하지 않으면
// 새로고침 뒤에도 소쿠리가 입력칸에 남는다. 우리 글임이 확실하고 전송 단추도
// 비활성인 경우만 지운다. 사람이 쓰던 초안은 절대 건드리지 않는다.
function 고장난에이전트초안정리() {
  const 입력 = 입력창찾기();
  if (!입력) return false;
  const 글 = 입력칸글(입력).trim();
  const 우리글 = 글.indexOf(규약.응답시작) === 0 || 글.indexOf(설치결과머리) === 0;
  if (!우리글 || 편집기가입력받았나(찾기(셀렉터.전송버튼))) return false;
  try {
    입력창비우기(입력);
    console.warn('[로컬에이전트] 전송 불가 상태로 남은 에이전트 초안을 정리했습니다.');
    return true;
  } catch (e) {
    return false;
  }
}

// ▶ 재개는 새 작업을 시작하는 단추가 아니다. 이전 전송이 실패해 남은
// 결과가 있으면 그 결과만 한 번 이어 보내고, 화면에 남은 오래된 소쿠리
// 초안은 현재 보낼 결과와 같을 때만 보존한다.
function 재개준비하기() {
  상태.진행 = null;
  상태.진행본때 = 0;

  // 보낼 결과가 이미 만들어진 상태에서 재개를 누르면, 검사()가 바로
  // 도구를 다시 돌리지는 않는다. 전송은 사람이 [다시 보내기]로 고른다.
  if (상태.보낼것대기) 상태.보류결과수동 = true;

  const 입력 = 입력창찾기();
  if (!입력) return;
  const 남은글 = 입력칸글(입력).trim();
  const 우리글 = 남은글.indexOf(규약.응답시작) === 0
    || 남은글.indexOf(설치결과머리) === 0;
  if (!우리글) return;

  const 보낼것 = 상태.보낼것대기
    ? (상태.보낼것대기.짧은텍스트 || 결과를글로줄이기(상태.보낼것대기.텍스트))
    : '';
  if (보낼것 && 들어갔나(입력, 보낼것)) return;
  try { 입력창비우기(입력); }
  catch (e) { console.warn('[로컬에이전트] 재개할 때 오래된 초안을 지우지 못했습니다.', e); }
}

function 설치결과글(결과) {
  const 눈손 = 결과.갈래 === '눈' || 결과.갈래 === '손';
  const 줄 = [
    설치결과머리,
    눈손
      ? '사용자가 ' + (결과.갈래 === '눈' ? '화면 보기' : '키보드·마우스 쓰기') + (결과.됨 ? ' 를 허용했습니다.' : ' 를 허용하지 않았습니다.')
      : '사용자가 설치 허용을 눌렀습니다.',
    '무엇 ' + String(결과.무엇 || ''),
    '상태 ' + (결과.됨 ? '성공' : '실패'),
  ];
  if (결과.판번호) 줄.push('버전 ' + 결과.판번호);
  if (결과.탈) 줄.push('이유 ' + String(결과.탈).slice(0, 500));
  if (결과.나온것) 줄.push('출력\n' + String(결과.나온것).slice(-2500));
  return 줄.join('\n').slice(0, 4000);
}

async function 내말살피기() {
  const 번호 = 대화번호();
  if (!번호 || 번호 !== 상태.대화번호) return;
  const 목록 = 모두찾기(셀렉터.사용자메시지);
  const el = 목록.length ? 목록[목록.length - 1] : null;
  if (!el) return;
  const 글 = String(el.innerText || el.textContent || '').trim();
  if (!글) return;
  const 열쇠 = 답변아이디(el, '글' + 지문(글));
  if (상태.남긴내말.has(열쇠)) return;

  const 옛말인가 = !상태.내말기록있음 && !상태.새대화에서옴
    && Date.now() - 상태.내말기준때 < 내말기준ms;
  if (옛말인가 || 사람말아닌가(글)) {
    상태.남긴내말.add(열쇠);
    await 내말기록남기기();
    return;
  }

  // 방이 아직 없으면(바구니가 안 나온 새 대화) 안 남기고 다음에 또 본다
  const 방 = 상태.지금방 || await 지금방확인();
  if (!방) return;
  await 대화남기기('사용자', 글, 'u:' + 열쇠);
  상태.남긴내말.add(열쇠);
  상태.새대화에서옴 = false;
  await 내말기록남기기();
}

// 바구니가 어느 답변에 있었는지까지 넣은 열쇠.
// 같은 바구니 글이라도 다음 답변에 또 나오면 다시 해야 한다.
// 답변은 ChatGPT가 붙이는 메시지 번호(data-message-id)로 가린다. 답 수로 가리면
// '긴 대화 가볍게' 가 옛 답을 덜어 낼 때 수가 줄어 다른 답과 열쇠가 겹친다.
function 처리열쇠(답변번호, 블록) {
  return 답변번호 + '#' + 지문(블록.원문);
}

// 메시지 번호. 예전엔 data-message-id, 지금은 data-chatgpt-search-message-ids.
const 메시지번호속성들 = ['data-chatgpt-search-message-ids', 'data-message-id'];

function 메시지번호(el) {
  if (!el || !el.getAttribute) return '';
  for (const 속성 of 메시지번호속성들) {
    let 곳 = el.getAttribute(속성) ? el : null;
    if (!곳 && el.closest) {
      try { 곳 = el.closest('[' + 속성 + ']'); } catch (e) { 곳 = null; }
    }
    const 번호 = 곳 && 곳.getAttribute(속성);
    if (번호) return String(번호).split(/[\s,]+/)[0];
  }
  return '';
}

function 답변아이디(el, 순번) {
  try {
    const 번호 = 메시지번호(el);
    if (번호) return 번호;
  } catch (e) { /* 넘어간다 */ }
  return String(순번);
}

// ── 방 이름은 ChatGPT가 지은 대화 제목을 그대로 쓴다 ─────────
// 에이전트가 따로 이름을 짓게 하면 한 번 더 왔다 갔다 해야 하고,
// 사용자가 왼쪽 목록에서 보는 이름과도 달라진다.

const 쓸모없는제목 = /^(chatgpt|새 채팅|new chat|chat\s*gpt)$/i;

// 왼쪽 목록에서 지금 대화의 이름을 읽는다.
// 주소가 .../c/<번호> 이므로 같은 번호를 가리키는 링크를 찾으면 된다.
function 목록속제목() {
  const 맞음 = location.pathname.match(/\/c\/([\w-]+)/);
  if (!맞음) return '';
  const 번호 = 맞음[1];
  for (const 링크 of 모두찾기(셀렉터.대화목록링크)) {
    const href = 링크.getAttribute('href') || '';
    if (href.indexOf(번호) === -1) continue;
    const 글 = 프로젝트이름떼기((링크.textContent || '').trim());
    if (글) return 글.slice(0, 60);
  }
  return '';
}

// ChatGPT 프로젝트 안의 대화는 왼쪽 목록 글자 뒤에 프로젝트 이름표가 붙는다.
// ('발로란트 AI 개발 계획' + '로컬 에이전트' → '발로란트 AI 개발 계획로컬 에이전트')
// 페이지 제목이 '<프로젝트> - <대화 제목>' 꼴이라 거기서 프로젝트 이름을 알아낸다.
function 프로젝트이름원문() {
  const 조각 = String(document.title || '').split(' - ');
  return 조각.length > 1 ? 조각[0].trim() : '';
}

// ChatGPT가 프로젝트를 아직 못 불러오면 이름 자리에 'Loading project' 를 띄운다.
// 그걸 받아 적으면 판의 묶음 이름이 망가지므로 빈 값으로 본다.
const 불러오는중이름 = /^(loading(\s+project)?|프로젝트\s*(불러오는|로드|로딩)\s*중.*|(불러오는|로드|로딩)\s*중.*)$/i;

function 쓸만한프로젝트이름(이름) {
  return !!이름 && !불러오는중이름.test(이름) && !/^chat\s*gpt$/i.test(이름);
}

// 먼저 화면 위 이동 경로(프로젝트 번호가 맞는 링크), 없으면 탭 제목 앞부분
function 프로젝트이름() {
  const 번호 = 프로젝트번호();
  try {
    for (const 링크 of 모두찾기(셀렉터.프로젝트경로)) {
      const 주소 = String((링크.getAttribute && 링크.getAttribute('href')) || '');
      const 글 = String(링크.textContent || '').trim();
      if (번호 && 주소.indexOf(번호) !== -1 && 쓸만한프로젝트이름(글)) return 글.slice(0, 60);
    }
  } catch (e) { /* 넘어간다 */ }
  const 이름 = 프로젝트이름원문();
  return 쓸만한프로젝트이름(이름) ? 이름 : '';
}

function 프로젝트이름떼기(글) {
  const 이름 = 프로젝트이름원문();
  if (이름 && 글.length > 이름.length && 글.endsWith(이름)) {
    return 글.slice(0, 글.length - 이름.length).trim();
  }
  return 글;
}

// 목록에서 못 찾으면 페이지 제목으로 때운다.
// 제목에는 'ChatGPT' 나 프로젝트 이름이 앞뒤로 붙으므로 떼어낸다.
function 제목에서() {
  let 제목 = (document.title || '').trim();
  제목 = 제목.replace(/^chat\s*gpt\s*[-|·]\s*/i, '');
  제목 = 제목.replace(/\s*[-|·]\s*chat\s*gpt\s*$/i, '');
  제목 = 제목.trim();
  if (!제목 || 쓸모없는제목.test(제목)) return '';
  return 제목.slice(0, 60);
}

function 대화제목() {
  return 목록속제목() || 제목에서();
}

// ChatGPT는 제목을 한 글자씩 타자 치듯 그린다. 그 중간에 잡으면 '발로란트 AI'
// 가 '발로' 로 굳는다(실제로 그랬다). 그래서 같은 제목이 제목안정ms 동안
// 그대로일 때만 믿는다. 사람이 판에서 직접 지은 이름은 건드리지 않는다.
const 제목안정ms = 2000;

async function 방이름맞추기() {
  if (!상태.지금방 || 상태.이름고정) return;
  const 제목 = 대화제목();
  if (!제목) return;

  const 이제 = Date.now();
  if (제목 !== 상태.제목후보) {
    상태.제목후보 = 제목;
    상태.제목본때 = 이제;
    return;
  }
  if (이제 - 상태.제목본때 < 제목안정ms) return;
  if (제목 === 상태.방이름 || 제목 === 상태.이름맞춰봄) return;
  상태.이름맞춰봄 = 제목;

  try {
    const 답 = await chrome.runtime.sendMessage({
      종류: '방짓',
      몸통: { 짓: '이름', 쪽번호: 상태.지금방, 이름: 제목, 자동: true, 방번호: 상태.지금방 },
    });
    if (답 && 답.됨) {
      상태.방이름 = 제목;
      상태.이름필요 = false;
      창에게('대화갱신');
    }
  } catch (e) { /* 넘어간다 */ }
}

// 지문값: 남기는 글과 화면 글이 다를 때(마크다운으로 바꿔 남길 때) 화면 글의 지문을 준다.
// 되돌림은 화면 글의 지문으로 맞춰 보므로 어긋나면 기록을 엉뚱하게 자른다.
async function 대화남기기(종류, 글, 지문값) {
  const 방 = 상태.지금방 || await 지금방확인();
  if (!방) return;
  try {
    await chrome.runtime.sendMessage({
      종류: '대화남기기2',
      // gpt 가 한 말에는 지문을 같이 남긴다. 되돌렸을 때 어디까지 지울지 알아야 한다.
      몸통: { 쪽번호: 방, 방번호: 방, 종류, 글, 나물: '',
              지문: 지문값 !== undefined ? 지문값 : (종류 === 'gpt' ? 지문(글 || '') : '') },
    });
    창에게('대화갱신');
  } catch (e) { /* 넘어간다 */ }
}

// ── 되돌림 알아채기 ───────────────────────────────────────────
// ChatGPT에서 내 말 옆 연필을 눌러 고치면 그 뒤 대화가 통째로 사라진다.
// 화면의 답변 지문 줄이 '앞부분만 남은 꼴' 로 짧아지면 되돌린 것이다.
// 그때 여기 기록도 같은 자리까지 잘라내야 없어진 일을 한 것처럼 보이지 않는다.

function 답변지문들(답변들) {
  return 답변들.map((el) => 지문(답변글(el).글 || ''));
}

async function 되돌렸나보기(답변들) {
  const 지금것 = 답변지문들(답변들);
  const 본것 = 상태.본답변지문들;

  // 답변 수가 줄어든 것만 되돌림으로 본다.
  // 되돌리면 고친 지점 뒤가 통째로 사라지므로 반드시 짧아진다.
  // (고친 뒤 새 답변이 붙으면서 마지막 하나가 달라질 수 있으니 내용은 안 따진다.
  //  무엇을 지울지는 서버가 뒤에서부터 훑으며 안전하게 정한다.)
  if (지금것.length >= 본것.length) {
    상태.본답변지문들 = 지금것;
    return;
  }

  // 화면이 옛 답을 덜어 내도(ChatGPT가 다시 불러오거나 할 때) 답 수가 준다. 그때 마지막으로 본 답은
  // 그대로 있다. 진짜 되돌림(연필로 고침)이면 마지막 답이 사라진다.
  // 이걸 안 가리면 서버의 방 대화 기록을 엉뚱하게 잘라 버린다.
  const 마지막본것 = 본것[본것.length - 1];
  if (마지막본것 && 지금것.indexOf(마지막본것) !== -1) {
    상태.본답변지문들 = 지금것;
    return;
  }

  상태.본답변지문들 = 지금것;
  상태.처리한지문.clear();       // 없어진 바구니는 다시 해도 된다
  상태.보낼것대기 = null;         // 되돌린 시점 뒤의 결과는 보낼 곳이 없다
  상태.승인대기 = null;
  await 처리기록남기기();
  상태.마지막기록텍스트 = '';
  상태.마지막텍스트 = '';
  상태.마지막보일텍스트 = '';
  상태.마지막답변수 = 지금것.length;
  상태.이번에고친것 = {};
  상태.헛돎횟수 = 0;
  상태.헛돎열쇠 = '';
  상태.다실패횟수 = 0;

  const 방 = 상태.지금방 || await 지금방확인();
  if (!방) return;

  try {
    const 답 = await chrome.runtime.sendMessage({
      종류: '대화남기기2',
      몸통: { 쪽번호: 방, 종류: '되돌리기', 남은지문들: 지금것 },
    });
    if (답 && 답.잘랐나) {
      알림('앞 시점으로 되돌렸습니다. 기록 ' + 답.지운건수 + '건을 지웠습니다.');
    } else {
      알림('앞 시점으로 되돌렸습니다.');
    }
    창에게('대화갱신');
  } catch (e) { /* 넘어간다 */ }
}

// 도구를 한 번 쓸 때마다 대화에 짧은 줄을 남긴다.
// 클로드가 "읽기 및 편집됨 foo.py +12 -3" 처럼 보여주는 것과 같은 자리다.
async function 도구줄남기기(나물이름, 요청, 결과) {
  const 성공 = !!(결과 && 결과.됨);
  const 대상 = (요청 && (요청['밭'] || 요청['불'] || 요청['일'] || 요청['향'] || 요청['창'])) || '';
  const 더함 = (결과 && 결과.더한줄) || 0;
  const 뺌 = (결과 && 결과.뺀줄) || 0;

  // 파일을 고쳤으면 이번 묶음 장부에 쌓는다
  if (성공 && (더함 || 뺌) && 요청['밭']) {
    const 열쇠 = 요청['밭'];
    const 칸 = 상태.이번에고친것[열쇠] || { 더한줄: 0, 뺀줄: 0, 번: 0 };
    칸.더한줄 += 더함;
    칸.뺀줄 += 뺌;
    칸.번 += 1;
    상태.이번에고친것[열쇠] = 칸;
  }

  let 꼬리 = '';
  if (!성공) 꼬리 = String((결과 && 결과.탈) || '실패').slice(0, 80);
  else if (더함 || 뺌) 꼬리 = '+' + 더함 + ' -' + 뺌;
  else if (결과 && 결과.끝번호 !== undefined && 결과.끝번호 !== null)
    꼬리 = 결과.끝번호 === 0 ? '잘 끝남' : '끝번호 ' + 결과.끝번호;
  else if (결과 && 결과.총줄 !== undefined) 꼬리 = 결과.총줄 + '줄';
  else if (결과 && 결과.건수 !== undefined) 꼬리 = 결과.건수 + '건';
  else if (결과 && 결과.개수 !== undefined) 꼬리 = 결과.개수 + '개';
  else if (결과 && 결과.진도 !== undefined) 꼬리 = 결과.진도;

  await 대화남기기('도구', JSON.stringify({
    이름: 사람말(나물이름),
    나물: 나물이름,
    대상: String(대상).split(줄바꿈)[0].slice(0, 80),
    찾는말: String((요청 && 요청['향']) || '').split(줄바꿈)[0].slice(0, 60),
    성공, 꼬리,
    귀띔: (결과 && 결과.귀띔) || '',
    턴: 상태.턴번호,
    걸린ms: (결과 && 결과._걸린ms) || 0,
    미리: 결과미리보기(결과),
    차이: (결과 && 결과._차이 && (결과._차이.줄들 || []).length) ? 결과._차이 : null,
  }));
}

const 줄바꿈 = String.fromCharCode(10);

// 결과에서 '펼쳐 보면 나올 것' 을 뽑는다.
// 클로드가 도구 줄 아래에 접어 두는 그 내용과 같은 자리다.
const 미리최대줄 = 30;
const 미리최대글자 = 300;

function 결과미리보기(결과) {
  if (!결과) return null;
  if (결과.됨 === false) {
    return { 갈래: '탈', 줄들: [String(결과.탈 || '실패').slice(0, 600)], 잘림: false };
  }
  // 앞에서부터 찾아 하나만 쓴다. 긴 글을 담는 키들이다.
  // 서버가 돌려주는 바깥 이름 기준이다 (aliases.py 응답키 와 짝).
  const 긴키 = ['속', '모양', '나온것', '기록'];
  for (const 키 of 긴키) {
    const 값 = 결과[키];
    if (typeof 값 !== 'string' || !값.trim()) continue;
    const 온줄 = 값.split(줄바꿈);
    return {
      갈래: 키 === '모양' ? '나무' : '글',
      줄들: 온줄.slice(0, 미리최대줄).map((줄) => 줄.slice(0, 미리최대글자)),
      잘림: 온줄.length > 미리최대줄,
    };
  }
  // 찾은 것 목록(미나리)
  const 걸림 = 결과['걸린것'];
  if (Array.isArray(걸림) && 걸림.length) {
    return {
      갈래: '목록',
      줄들: 걸림.slice(0, 미리최대줄).map((항목) => (
        항목 && typeof 항목 === 'object'
          ? Object.values(항목).join('  ').slice(0, 미리최대글자)
          : String(항목).slice(0, 미리최대글자)
      )),
      잘림: 걸림.length > 미리최대줄,
    };
  }
  return null;
}

// 한 묶음이 끝나면 손댄 파일을 모아 한 장으로 낸다.
async function 요약내기() {
  const 밭들 = Object.keys(상태.이번에고친것);
  if (밭들.length === 0) return;
  const 목록 = 밭들.map((밭) => ({ 밭, ...상태.이번에고친것[밭] }));
  상태.이번에고친것 = {};
  await 대화남기기('요약', JSON.stringify({ 목록 }));
}

