// (이 대화 것을 같이 쓰므로 첫 답부터 기준이 생긴다. 다른 대화 것은 3개 쌓여야 쓴다.)
// 이 대화의 최근 느림연속 개 답이 모두 평소의 느림비율 보다 느리면 표시해 두고,
