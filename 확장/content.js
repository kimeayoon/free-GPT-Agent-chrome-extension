// 대화가 길면 한도 안내가 뜨기 전에 먼저 '1초에 몇 글자' 로 느려진다.
// 답마다 글자를 쓰기 시작한 뒤의 속도를 재고('생각 중' 시간은 뺀다), 평소 속도와 견준다.
