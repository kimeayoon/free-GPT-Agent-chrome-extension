function 창에게(짓, 값) {
  try {
    const 결과 = chrome.runtime.sendMessage({ 종류: '탭→창', 짓, 값 });
    if (결과 && 결과.catch) 결과.catch(() => {});   // 패널이 닫혀 있으면 그냥 넘긴다
  } catch (e) { /* 넘어간다 */ }
}

function 심장뛰기() {
  const 이제 = Date.now();
  if (상태.마지막돈때) {
    const 틈 = 이제 - 상태.마지막돈때;
    if (틈 > 상태.최대틈ms) 상태.최대틈ms = 틈;
  }
  상태.마지막돈때 = 이제;
  상태.돈횟수 += 1;
}

