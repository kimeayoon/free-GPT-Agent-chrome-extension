// 바구니를 찾아 줄 단위 형식을 풀어낸다. 표시 문자열은 protocol.js 에서 온다.
//
// 형식:
//   나물 열무
//   밭 inventory▸report.py
//   앞《
//       return start < d < end
//   》
//
// 한 줄 값 : "키 값"  (첫 공백에서 갈린다)
// 여러 줄  : "키《" 로 열고, 》 만 있는 줄로 닫는다. 안쪽은 손대지 않는다.

const 블록정규식 = new RegExp(
  정규식이스케이프(규약.요청시작) + '([\\s\\S]*?)' + 정규식이스케이프(규약.요청끝),
  'g'
);

// ``` 로 감싸 왔으면 벗긴다
function 껍질벗기기(원문) {
  let s = 원문.replace(/^\s*```[a-zA-Z]*\s*$/gm, '');
  return s.replace(/^\n+|\n+$/g, '');
}

// 파일 내용이 들어가는 묶음. 한 글자도 건드리지 않고, 닫는 표시도 》 만 있는 줄만 본다.
const 내용키 = ['앞', '뒤', '속'];

// 《 》 짝이 맞나 (닫는 것이 먼저 나오면 안 맞음)
function 짝맞나(글) {
  let 깊이 = 0;
  for (const 글자 of 글) {
    if (글자 === 규약.묶음시작) 깊이++;
    else if (글자 === 규약.묶음끝 && --깊이 < 0) return false;
  }
  return 깊이 === 0;
}

// "키《뒤" 로 쪼갠다. 키가 빈칸 없는 한 낱말일 때만 —
// "말 《책》을 읽고" 처럼 값이 《 로 시작하는 한 줄은 묶음이 아니다.
function 한낱말묶음(줄) {
  const 손질 = 줄.trim();
  const 자리 = 손질.indexOf(규약.묶음시작);
  if (자리 <= 0) return null;
  const 키 = 손질.slice(0, 자리).trim();
  if (!키 || /\s/.test(키)) return null;
  return { 키, 뒤: 손질.slice(자리 + 규약.묶음시작.length) };
}

// 한 줄에 열고 닫은 묶음인가:  일《 무엇을 · 어디서 》  (GPT-5.6 은 짧은 값을 이렇게 쓴다)
// 맞으면 { 키, 속 }, 아니면 null.
function 한줄묶음(줄) {
  const 쪼갬 = 한낱말묶음(줄);
  if (!쪼갬 || !쪼갬.뒤.endsWith(규약.묶음끝)) return null;
  const 속 = 쪼갬.뒤.slice(0, -규약.묶음끝.length);
  if (!짝맞나(속)) return null;
  // 파일 내용은 그대로 둔다(들여쓰기가 살아야 한다). 《 x 》 처럼 양쪽에 한 칸씩 띄운 모양일 때만 그 한 칸을 뗀다.
  // 나머지 키는 양쪽 빈칸을 다 뗀다.
  if (!내용키.includes(쪼갬.키)) return { 키: 쪼갬.키, 속: 속.trim() };
  return { 키: 쪼갬.키, 속: /^ \S[\s\S]* $/.test(속) || /^ \S $/.test(속) ? 속.slice(1, -1) : 속 };
}

// 이 줄이 여러 줄 묶음을 여는가. 열면 { 키, 첫줄들 }, 아니면 null.
//   "일《"       → 다음 줄부터 내용
//   "일《첫 줄"  → 그 줄부터 내용 (키는 한 낱말, 같은 줄에 》 가 없을 때만)
function 묶음여나(줄) {
  const 다듬 = 줄.trimEnd();
  if (다듬.endsWith(규약.묶음시작)) {
    return { 키: 다듬.slice(0, -규약.묶음시작.length).trim(), 첫줄들: [] };
  }
  const 쪼갬 = 한낱말묶음(줄);
  if (쪼갬 && 쪼갬.뒤.indexOf(규약.묶음끝) === -1) return { 키: 쪼갬.키, 첫줄들: [쪼갬.뒤] };
  return null;
}

// 이 줄이 묶음을 닫는가. 닫으면 닫는 표시 앞에 남은 내용(없으면 null)을 { 남은 } 으로, 아니면 null.
//   "》"          → 닫음
//   "마지막 줄》" → 닫음 (파일 내용 묶음은 빼고 — 내용이 》 로 끝날 수 있다)
function 묶음닫나(줄, 키) {
  const 손질 = 줄.trim();
  if (손질 === 규약.묶음끝) return { 남은: null };
  if (!내용키.includes(키) && 손질.endsWith(규약.묶음끝)
      && 짝맞나(손질.slice(0, -규약.묶음끝.length))) {
    return { 남은: 줄.trimEnd().slice(0, -규약.묶음끝.length) };
  }
  return null;
}

// 한 줄 값을 키에 맞는 꼴로 (숫자 · 목록 · 글)
function 한줄값(키, 값) {
  if (숫자키.includes(키)) {
    const n = Number(값);
    if (!Number.isFinite(n)) return { 오류: '"' + 키 + '" 는 숫자여야 합니다: ' + 값 };
    return { 값: n };
  }
  if (목록키.includes(키)) return { 값: 값.split(/\s*,\s*/).filter((s) => s) };
  return { 값 };
}

// 줄 단위 본문 → 객체
function 본문풀기(본문) {
  const 줄들 = 껍질벗기기(본문).split('\n');
  const 결과 = {};
  let i = 0;

  while (i < 줄들.length) {
    const 줄 = 줄들[i];
    if (!줄.trim()) { i++; continue; }

    // 한 줄에 열고 닫은 묶음인가?
    const 한줄 = 한줄묶음(줄);
    if (한줄) {
      const 바꾼 = 한줄값(한줄.키, 한줄.속);
      if (바꾼.오류) return { 오류: 바꾼.오류 };
      결과[한줄.키] = 바꾼.값;
      i++;
      continue;
    }

    // 여러 줄 묶음인가?
    const 연것 = 묶음여나(줄);
    if (연것) {
      const 키 = 연것.키;
      const 모음 = 연것.첫줄들.slice();
      i++;
      let 닫힘 = false;
      while (i < 줄들.length) {
        const 닫음 = 묶음닫나(줄들[i], 키);
        if (닫음) {
          if (닫음.남은 !== null) 모음.push(닫음.남은);
          닫힘 = true;
          i++;
          break;
        }
        모음.push(줄들[i]);
        i++;
      }
      if (!닫힘) {
        return { 오류: '"' + 키 + '" 의 ' + 규약.묶음끝 + ' 가 없습니다.' };
      }
      결과[키] = 목록키.includes(키)
        ? 모음.map((s) => s.trim()).filter((s) => s)
        : 모음.join('\n');
      continue;
    }

    // 한 줄 값
    const 자름 = 줄.trim().match(/^(\S+)\s+([\s\S]*)$/);
    if (!자름) {
      return { 오류: '알아볼 수 없는 줄: ' + 줄.trim().slice(0, 40) };
    }
    const 바꾼 = 한줄값(자름[1], 자름[2].trim());
    if (바꾼.오류) return { 오류: 바꾼.오류 };
    결과[자름[1]] = 바꾼.값;
    i++;
  }

  return { 값: 결과 };
}

// 자리 구분 기호를 빗금으로 되돌린다(서버는 빗금을 쓴다).
function 자리정리(객체) {
  for (const 키 of Object.keys(객체)) {
    if (typeof 객체[키] === 'string') {
      객체[키] = 객체[키].split(규약.자리구분).join('/');
    }
  }
  return 객체;
}

// GPT 가 도구로 직접 볼 수 있는 결과(로그 · 체크포인트 · 지표)를 '누가 보내 줘야 하는 것처럼' 기다리는 말인가.
// 예) "마지막 결과와 checkpoint 확인 결과를 받아야 다음 검증을 진행할 수 있어" · "로그 결과가 오면 바로 이어갈게".
// 아무도 그것을 따로 보내 주지 않는다 — 도구(고사리 · 열무)로 스스로 확인해야 한다.
// '필요하면 알려줘' 같은 흔한 맺음말은 걸리지 않게 결과·로그 낱말과 가까운 기다림 표현만 본다.
const 결과기다림꼴들 = [
  /(결과|로그|출력|체크포인트|checkpoint|지표)[^.\n]{0,40}(받아야|받으면|받은 뒤|받고 나서|받는 대로|오면|오는 대로|도착하면|도착하는 대로|필요해|필요합니다|필요하다|보내 ?주|붙여 ?주)/i,
  /(받아야|보내 ?주|붙여 ?주)[^.\n]{0,30}(진행할 수 있|이어갈 수 있|이어 갈 수 있|검증할 수 있|확인할 수 있)/,
];

// "여기서 바로 호출할 수 없어" · "직접 열 수는 없어" · "도구가 연결되어 있지 않아" — 바구니를 쓰면 되는데 못 한다고 믿는 말
const 못한다는말꼴들 = [
  /(직접|바로|여기서)[^.\n]{0,60}(호출|실행|열|읽|접근)[^.\n]{0,10}(수는? 없|수가 없|못 해|못해)/,
  /(도구|에이전트|기능)[^.\n]{0,24}(연결되어 있지 않|연결돼 있지 않|연결이 안)/,
];

function 못한다는말(글) {
  const 본문 = String(글 || '').replace(/```[\s\S]*?```/g, ' ');
  if (!본문.trim()) return false;
  if (본문.indexOf(규약.요청시작) !== -1 || 본문.indexOf(규약.물음시작) !== -1) return false;
  return 못한다는말꼴들.some((식) => 식.test(본문));
}

// "다음은 변경 계획을 먼저 세우고 진행한다." — 다음에 할 일을 말로만 적고 바구니도 【물음】도 없이 답을 끝낸 것.
// 아무도 그 일을 대신 시작해 주지 않아 일이 멈춘다. 답의 마지막 줄만 본다(보고 중간의 '다음은' 은 안 걸리게).
// 사용자의 승인·결정을 기다리는 말(승인 · 결정 · 선택 · 알려 주 · 말씀 · 답해)은 옳게 기다리는 것이니 안 건다.
const 말뿐인끝맺음시작 = /(다음은|다음으로|다음엔|이어서|이제|곧|바로)/;
// 동사 어미가 없는 끝('…검증 진행.' · '…학습 시작')도 같다 — 실제 사고: '사용자가 할 일: 없음. 다음은 3단계 검증 진행.' 으로 끝내고 멈췄다
const 말뿐인끝맺음동사 = /(진행|시작|실행|확인|수정|비교|검증|이어감|이어 감|진행한다|진행할게|진행하겠다|진행합니다|진행하겠습니다|시작한다|시작할게|시작하겠다|시작합니다|시작하겠습니다|하겠다|할게|하겠습니다|이어간다|이어갈게|이어 가겠다|세운다|세울게|만든다|만들게|확인한다|확인할게|읽는다|읽을게|실행한다|실행할게|수정한다|수정할게|고친다|고칠게|비교한다|비교할게)[ .!]*$/;
const 사용자를기다리는말 = /(승인|결정|선택|알려 ?주|말씀|답해|골라|허락|허용|원하시|괜찮으시)/;

// 말꼴을 다 적을 수는 없다("만들면 돼" · "이어서 진행한다" · "확인할 항목: 1…5" 처럼 끝나는 것도 실제로 있었다).
// 그래서 모양으로도 본다: 바구니도 【물음】도 없고, 끝에 '사용자가 할 일' 줄(설명서 나-3: 할 일이 없으면 "사용자가 할 일 없음")이 없고,
// 끝부분(마지막 300자)이 앞으로 할 일을 말하고 있으면 — 일을 마친 보고가 아니라 하다 만 답이다.
const 앞으로할일말 = /(다음으로|다음은|다음에는|다음 단계|이후|이어서|앞으로|예정|확인할 항목|할 일은)/;

function 말만하고끝낸말(글) {
  const 원문 = String(글 || '');
  // 바구니·물음이 있으면(코드블록으로 감싼 것도) 이미 무엇인가 한 답이다
  if (원문.indexOf(규약.요청시작) !== -1 || 원문.indexOf(규약.물음시작) !== -1) return false;
  const 본문 = 원문.replace(/```[\s\S]*?```/g, ' ');
  const 줄들 = 본문.split('\n').map((줄) => 줄.trim()).filter((줄) => 줄);
  const 끝 = 줄들[줄들.length - 1] || '';
  if (!끝 || 사용자를기다리는말.test(끝)) return false;
  const 시작 = 끝.search(말뿐인끝맺음시작);
  if (시작 !== -1 && 말뿐인끝맺음동사.test(끝.slice(시작))) return true;
  const 끝토막 = 본문.trim().slice(-300);
  return !/사용자가 할 일/.test(끝토막) && 앞으로할일말.test(끝토막);
}

function 결과기다림말(글) {
  const 본문 = String(글 || '').replace(/```[\s\S]*?```/g, ' ');
  if (!본문.trim()) return false;
  if (본문.indexOf(규약.요청시작) !== -1 || 본문.indexOf(규약.물음시작) !== -1) return false;
  return 결과기다림꼴들.some((식) => 식.test(본문));
}

// 바구니 하나에 나물을 둘 이상 적어 온 것(GPT-5.6 이 '몰아 담기' 를 이렇게 쓴다)을 나물마다 나눈다.
// 둘째 '나물' 줄부터 새 조각. 《 》 안쪽의 '나물' 줄은 파일 내용이므로 건드리지 않는다.
function 나물별로나누기(본문) {
  const 줄들 = 껍질벗기기(본문).split('\n');
  const 조각들 = [];
  let 지금 = [];
  let 묶음키 = null;              // null 이면 묶음 밖
  let 나물봄 = false;
  for (const 줄 of 줄들) {
    if (묶음키 !== null) {
      지금.push(줄);
      if (묶음닫나(줄, 묶음키)) 묶음키 = null;
      continue;
    }
    const 나물줄 = 줄.trim().split(/\s+/)[0] === 규약.이름키;
    if (나물줄 && 나물봄) {
      조각들.push(지금.join('\n'));
      지금 = [];
    }
    if (나물줄) 나물봄 = true;
    const 연것 = 묶음여나(줄);
    if (연것) 묶음키 = 연것.키;
    지금.push(줄);
  }
  조각들.push(지금.join('\n'));
  return 조각들;
}

// '하는말' 값을 한 줄 글로 다듬는다. 비었거나 '없음' 이면 빈 글.
function 하는말다듬기(값) {
  const 글 = String(값 === null || 값 === undefined ? '' : 값).replace(/\s+/g, ' ').trim();
  if (글 === 규약.빈값) return '';
  return 글.length > 200 ? 글.slice(0, 199) + '…' : 글;
}

// 텍스트에서 바구니를 모두 뽑는다.
// 반환: [{ 원문, 요청, 오류, 하는말 }]
function 요청블록추출(텍스트) {
  if (!텍스트 || 텍스트.indexOf(규약.요청시작) === -1) return [];

  const 결과 = [];
  블록정규식.lastIndex = 0;
  let m;
  while ((m = 블록정규식.exec(텍스트)) !== null) {
    나물별로나누기(m[1]).forEach((조각, 순번) => {
      // 원문은 '이미 한 바구니인가' 를 가리는 열쇠가 된다 — 나눈 조각끼리 겹치지 않게 순번을 붙인다
      const 항목 = { 원문: 순번 === 0 ? m[0] : m[0] + '\n#' + (순번 + 1), 요청: null, 오류: null };
      const 푼것 = 본문풀기(조각);

      if (푼것.오류) {
        항목.오류 = 푼것.오류;
      } else if (!푼것.값[규약.이름키]) {
        항목.오류 = '"' + 규약.이름키 + '" 줄이 없습니다.';
      } else {
        // '하는말' 은 서버 도구의 칸이 아니다 — 떼어서 따로 들고 있는다(서버로 보내면 '넣은 값이 맞지 않습니다')
        if (푼것.값[규약.하는말키] !== undefined) {
          항목.하는말 = 하는말다듬기(푼것.값[규약.하는말키]);
          delete 푼것.값[규약.하는말키];
        }
        항목.요청 = 자리정리(푼것.값);
      }
      결과.push(항목);
    });
  }
  return 결과;
}

// ── 결과를 줄 단위 글로 되돌린다 ────────────────────────────────

function 값을글로(키, 값) {
  if (값 === null || 값 === undefined || 값 === '') {
    return 키 + ' ' + 규약.빈값;
  }
  if (typeof 값 === 'boolean') {
    return 키 + ' ' + (값 ? 규약.참 : 규약.거짓);
  }
  if (Array.isArray(값)) {
    if (값.length === 0) return 키 + ' ' + 규약.빈값;
    const 줄들 = 값.map((항목) => {
      if (항목 && typeof 항목 === 'object') {
        return Object.values(항목).join(' · ');
      }
      return String(항목);
    });
    return 키 + 규약.묶음시작 + '\n' + 줄들.join('\n') + '\n' + 규약.묶음끝;
  }
  if (값 && typeof 값 === 'object') {
    return 키 + 규약.묶음시작 + '\n' + 결과를글로(값) + '\n' + 규약.묶음끝;
  }
  const 글 = String(값);
  if (글.indexOf('\n') !== -1) {
    return 키 + 규약.묶음시작 + '\n' + 글 + '\n' + 규약.묶음끝;
  }
  return 키 + ' ' + 글;
}

// '_' 로 시작하는 키는 판에서만 쓰는 값이다(예: _차이).
// GPT 에게 보내면 대화창 글자만 잡아먹으므로 여기서 걸러낸다.
function 결과를글로(객체) {
  return Object.keys(객체)
    .filter((키) => 키.charAt(0) !== '_')
    .map((키) => 값을글로(키, 객체[키]))
    .join('\n');
}

// 같은 바구니를 두 번 처리하지 않으려고 쓰는 짧은 지문.
function 지문(문자열) {
  let h = 0;
  for (let i = 0; i < 문자열.length; i++) {
    h = (h * 31 + 문자열.charCodeAt(i)) | 0;
  }
  return h + ':' + 문자열.length;
}
