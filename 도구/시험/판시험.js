// 진짜 브라우저처럼, 본문을 비우면 굴리는 칸의 자리가 맨 위(0)로 돌아가게 흉내 낸다
function 굴림흉내(판, 자리, 전체높이, 보이는높이) {
  const 흐름 = 판.표['흐름'];
  const 본문 = 판.표['본문'];
  흐름.scrollTop = 자리;
  흐름.scrollHeight = 전체높이;
  흐름.clientHeight = 보이는높이;
  const 원래 = Object.getOwnPropertyDescriptor(Object.getPrototypeOf(본문), 'textContent');
  Object.defineProperty(본문, 'textContent', {
    configurable: true,
    get() { return 원래.get.call(this); },
    set(값) { 원래.set.call(this, 값); if (값 === '') { 흐름.scrollTop = 0; 흐름.비운수 = (흐름.비운수 || 0) + 1; } },
  });
  return 흐름;
}

