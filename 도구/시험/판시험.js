// panel.html 에 있는 id 를 그대로 뽑아 가짜 문서를 만든다.
// 이렇게 하면 HTML 에서 id 를 지웠는데 js 가 아직 찾는 경우도 여기서 걸린다.
function 판의아이디들() {
  const html = fs.readFileSync(path.join(확장칸, 'panel.html'), 'utf-8');
  return [...html.matchAll(/id="([^"]+)"/g)].map((m) => m[1]);
}

function 판차리기(설정 = {}) {
  const { 뿌리, 표, 문서, 듣개들 } = 문서만들기(판의아이디들());
  const 보낸쪽지 = [];
  const 탭쪽지 = [];
  const 탭옮김 = [];
  let 서버꺼짐 = !!설정.서버꺼짐;

  const 저장소 = Object.assign({}, 설정.저장소 || {});
  const 상자 = {
    console: { log: () => {}, warn: () => {}, error: () => {} },
    setTimeout, clearTimeout, setInterval: () => 0, clearInterval,
    Date, JSON, Math, Set, Map, Promise, Object, Array, String, Number, URL,
    document: 문서,
    location: { pathname: '/' },
    localStorage: {
      getItem: (k) => (k in 저장소 ? 저장소[k] : null),
      setItem: (k, v) => { 저장소[k] = String(v); },
    },
    chrome: {
      runtime: {
        onMessage: { addListener: (f) => { 상자.__받는이 = f; } },
        sendMessage: async (쪽지) => {
          보낸쪽지.push(쪽지);
          if (서버꺼짐) return 꺼진서버();
          if (쪽지.종류 === '서버확인') {
            return { success: true, version: '1.17.0', 도구목록: new Array(26), 등급: '전부' };
          }
          if (쪽지.종류 === '방나무') return 설정.나무 || 빈나무();
          if (쪽지.종류 === '칸보기') {
            if (설정.칸보기) return 설정.칸보기(쪽지.몸통 || {});
            return { 됨: false, 탈: '일할 곳을 먼저 고르세요.' };
          }
          if (쪽지.종류 === '계획보기') {
            return 설정.계획 || { 됨: true, 일: null, 차례: [] };
          }
          if (쪽지.종류 === '도구실행') {
            return 설정.도구답 ? 설정.도구답(쪽지.요청 || {}) : { 됨: true };
          }
          if (쪽지.종류 === '받아오기목록') return { 됨: true, 기다림: 설정.받아오기 || [], 허가중: 설정.허가중 || [] };
          if (쪽지.종류 === '받아오기처리') {
            if (쪽지.그만 !== undefined && !설정.받아오기처리) return { 됨: true, 거둠: 1, 기다림: [], 허가중: [] };
            return 설정.받아오기처리
              ? 설정.받아오기처리(쪽지)
              : { 됨: true, 열쇠: 쪽지.열쇠, 끝번호: 0, 기다림: [] };
          }
          if (쪽지.종류 === '예약') return { 됨: true, 예약들: 설정.예약들 || [] };
          return { 됨: true };
        },
      },
      windows: { getCurrent: async () => (설정.내창 === null ? null : { id: 설정.내창 === undefined ? 1 : 설정.내창 }) },
      tabs: {
        // 설정.창들 = { 창번호: [탭…] } 이면 windowId · lastFocusedWindow 를 따진다(없으면 늘 1번 탭)
        query: async (조건 = {}) => {
          if (!설정.창들) return [{ id: 1 }];
          if (조건.windowId !== undefined) return 설정.창들[조건.windowId] || [];
          if (조건.lastFocusedWindow) return 설정.창들[설정.마지막포커스창] || [];
          return Object.values(설정.창들).flat();
        },
        get: async () => ({ id: 1, url: 설정.현재주소 || 'https://chatgpt.com/' }),
        sendMessage: async (탭, 쪽지) => { 탭쪽지.push(쪽지); return 설정.탭답 || { 됨: true }; },
        update: async (탭, 바꿀것) => { 탭옮김.push({ 탭, ...바꿀것 }); return { id: 탭 }; },
      },
    },
  };
  상자.window = 상자;
  상자.globalThis = 상자;
  상자.innerWidth = 400;
  상자.innerHeight = 800;

  const 문맥 = vm.createContext(상자);
  for (const 이름 of ['protocol.js', 'parser.js', 'i18n.js']) {
    vm.runInContext(fs.readFileSync(path.join(확장칸, 이름), 'utf-8'), 문맥, { filename: 이름 });
  }
  vm.runInContext(fs.readFileSync(path.join(확장칸, 'panel.js'), 'utf-8'), 문맥,
                  { filename: 'panel.js' });

  return { 뿌리, 표, 문맥, 보낸쪽지, 탭쪽지, 탭옮김,
           문서쏘기: (갈래, 사건 = {}) => (듣개들[갈래] || []).forEach((f) => f(사건)),
           서버끄기: () => { 서버꺼짐 = true; },
           서버켜기: () => { 서버꺼짐 = false; },
           돌리기: (글) => vm.runInContext(글, 문맥),
           글자: () => 뿌리.글자뽑기() };
}

