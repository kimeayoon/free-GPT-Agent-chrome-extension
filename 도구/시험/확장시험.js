// 크롬은 안 보이는 탭의 타이머를 1초 단위로 늦추고, 5분 넘게 숨으면 1분에 한 번만 돌린다.
// 박동(서비스 워커 → 탭 메시지)은 안 늦춰지므로, 안쪽 대기도 박동으로 깨워야 한다.

async function 시험_타이머가_멈춘_숨은_탭에서도_대기는_박동으로_풀린다() {
  const 판 = 판차리기();
  await 잠깐(80);
  // 숨은 탭: setTimeout 이 아예 안 울린다고 친다
  판.돌리기('globalThis.__옛타이머 = setTimeout; globalThis.setTimeout = () => 0;');
  판.돌리기('globalThis.__풀림 = false; 잠깐(120).then(() => { globalThis.__풀림 = true; });');
  판.돌리기('박동으로깨우기()');
  await 잠깐(0);
  확인('때가 되기 전의 박동은 대기를 깨우지 않는다', 판.돌리기('__풀림') === false);
  await 잠깐(150);
  확인('  타이머가 안 울려도, 시간이 지난 뒤 박동이 오면 대기가 풀린다', 판.돌리기('__풀림') === false);
  판.돌리기('박동으로깨우기()');
  await 잠깐(0);
  확인('  (박동이 오자 풀렸다)', 판.돌리기('__풀림') === true);
  확인('  풀린 대기는 목록에서 빠진다', 판.돌리기('기다리는중.size') === 0);

  판.돌리기('globalThis.__세기 = 0; Promise.all([잠깐(10), 잠깐(10), 잠깐(5000)]).then(() => { globalThis.__세기 = 3; }); 잠깐(10).then(() => { globalThis.__세기 += 1; });');
  await 잠깐(30);
  판.돌리기('박동으로깨우기()');
  await 잠깐(0);
  확인('  긴 대기는 그대로 두고 때가 된 것만 깨운다', 판.돌리기('기다리는중.size') === 1, 판.돌리기('기다리는중.size'));
  판.돌리기('globalThis.setTimeout = __옛타이머;');
}

