function 예약서버(설정 = {}) {
  const 기록 = { 물음: 0, 보냄: [] };
  let 남음 = 설정.몇번 === undefined ? 1 : 설정.몇번;
  const 답 = (몸통) => {
    if (몸통.짓 === '때된것') {
      기록.물음 += 1;
      if (남음 <= 0) return { 됨: true, 예약: null };
      return { 됨: true, 예약: { 번호: 'r1', 간격: '1분', 보낼글: '⏰ 예약 알림 (1/3, 1분마다)\n학습 상태 보고' } };
    }
    if (몸통.짓 === '보냄') { 남음 -= 1; 기록.보냄.push(몸통); return { 됨: true }; }
    return { 됨: true };
  };
  return { 기록, 답 };
}

