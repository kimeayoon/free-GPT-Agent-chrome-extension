// ── 2026-09 ChatGPT 새 화면 구조 ────────────────────────────────
// data-message-author-role · data-message-id · <pre> 가 없어졌다(형님 Chrome 에서 확인).
// 답 덩어리: data-chatgpt-search-unit-key="…:assistant", 번호: data-chatgpt-search-message-ids,
// 코드블록: <div data-markdown-copy="code-block"> 안의 <code>, 답 앞에 화면 읽기용 'ChatGPT 답변:'.

function 새구조답(바구니글, 번호) {
  const 코드 = { innerText: 바구니글, textContent: 바구니글, nodeType: 1, tagName: 'CODE', childNodes: [] };
  return {
    innerText: 'ChatGPT 답변:\n일반 텍스트\n' + 바구니글,
    getAttribute: (k) => (k === 'data-chatgpt-search-message-ids' ? 번호
      : k === 'data-chatgpt-search-unit-key' ? 'fallback-turn-1:2:assistant' : null),
    querySelectorAll: (고른것) => (고른것 === '[data-markdown-copy="code-block"] code' ? [코드] : []),
  };
}

