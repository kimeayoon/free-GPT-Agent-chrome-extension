const 잠깐 = (ms) => new Promise((r) => setTimeout(r, ms));

// 검사()는 한 번으로 안 끝난다.
// 먼저 답이 바뀐 것을 알아채고, 안정대기가 지나야 비로소 처리한다.
// 그래서 시험에서는 '안정시각을 과거로 밀고 몇 번 돌리기' 를 해 준다.
async function 끝까지돌리기(판, 횟수 = 6) {
  for (let i = 0; i < 횟수; i++) {
    // 이 헬퍼는 논리 흐름 시험용이다. 전송 간격은 별도 시험에서 검사한다.
    판.돌리기('상태.안정시각 = 0; 상태.마지막결과보낸때 = 0;');
    await 판.돌리기('검사()');
    await 잠깐(25);
  }
}

