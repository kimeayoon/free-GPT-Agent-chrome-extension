# -*- coding: utf-8 -*-
"""설명서 — 모든 프로젝트의 GPT 가 먼저 읽고 따라야 할 공통 규칙.

ChatGPT 프로젝트 지침은 8000자 한도라 규칙을 못 담는다. 그래서 규칙은 파일
(문서/에이전트_설명서.md)에 두고, 숙주(새 대화의 첫 호출)와 넘김 파일이 GPT 에게 실어 보낸다.
사용자가 그 파일을 고치면 다음 대화부터 바로 바뀐다(서버를 다시 켤 필요가 없다).

프로젝트 폴더에 AGENTS.md · CLAUDE.md 가 있으면 그 이름과 크기를 알려, GPT 가 열무로 읽게 한다.
글을 합쳐 싣지는 않는다 — 프로젝트 규칙 파일은 15KB 가 넘기도 한다.
"""

from pathlib import Path

import sandbox

설명서파일 = Path(__file__).resolve().parent.parent / "문서" / "에이전트_설명서.md"
사람용표시 = "<!-- 여기부터 사람용 메모"        # 이 줄부터 아래는 GPT 에게 안 보낸다
최대글자 = 6000
프로젝트규칙이름 = ("AGENTS.md", "CLAUDE.md")


def 설명서글() -> str:
    """GPT 에게 보낼 설명서. 파일이 없거나 비면 빈 글(숙주·넘김은 그래도 돌아간다)."""
    try:
        글 = 설명서파일.read_text(encoding="utf-8")
    except OSError:
        return ""
    자리 = 글.find(사람용표시)
    if 자리 != -1:
        글 = 글[:자리]
    글 = 글.strip()
    if len(글) > 최대글자:
        글 = 글[:최대글자].rstrip() + "\n… (설명서가 길어 여기서 잘렸습니다)"
    return 글


def 프로젝트규칙() -> list:
    """지금 방의 일할 폴더 맨 위에 있는 규칙 파일들. [{이름, 크기}]"""
    try:
        기준 = sandbox.기준자리()
    except Exception:
        return []
    목록 = []
    for 이름 in 프로젝트규칙이름:
        파일 = Path(기준) / 이름
        try:
            if 파일.is_file():
                목록.append({"이름": 이름, "크기": 파일.stat().st_size})
        except OSError:
            continue
    return 목록


def _크기글(바이트: int) -> str:
    return f"{바이트 / 1024:.1f}KB" if 바이트 >= 1024 else f"{바이트}B"


def 프로젝트규칙안내(목록: list) -> str:
    if not 목록:
        return ""
    이름들 = ", ".join(f"{x['이름']} ({_크기글(x['크기'])})" for x in 목록)
    return (f"이 프로젝트에는 규칙 파일이 있습니다: {이름들}. 일을 시작하기 전에 열무로 읽고 따르세요"
            "(큰 파일은 첫줄/끝줄로 나눠 읽습니다). 위 설명서와 겹치면 더 엄격한 쪽을 따르고, "
            "서로 부딪치면 짐작하지 말고 사용자에게 물으세요.")


# ── 대화마다 처음 한 번은 반드시 읽게 한다 ──
# 프로젝트 지침(8000자)에 못 담은 규칙은 이 설명서에 있다. GPT 가 숙주를 안 부르거나(기존 대화·넘김 뒤) 잊어도,
# 그 대화(방+ChatGPT 대화 번호)에서 처음 부른 도구의 결과에 설명서를 자동으로 얹는다 — 도구가 무엇이든, 실패해도.
# 서버를 다시 켜면 한 번 더 간다(기록은 메모리에만 있다). 넘김 파일에 실어 보낸 방은 새 대화에서 또 안 얹는다.
_보낸곳: dict = {}              # 방 쪽번호 → 보낸 ChatGPT 대화 번호(없으면 ''), 넘김에 실었으면 '<넘김>'
_넘김표 = "<넘김>"


def _지금대화() -> tuple:
    """(방 쪽번호, 대화 번호). 방을 모르면 ('', '')."""
    try:
        import rooms
        방 = rooms.지금방() or {}
    except Exception:
        return "", ""
    return 방.get("쪽번호") or "", 방.get("대화") or ""


def 보냈나(방: str = "", 대화: str = "") -> bool:
    if not 방:
        방, 대화 = _지금대화()
    기록 = _보낸곳.get(방)
    return 기록 is not None and (기록 == 대화 or 기록 == _넘김표)


def 보냈다고적기(방: str = "", 대화: str = "") -> None:
    if not 방:
        방, 대화 = _지금대화()
    if 방:
        _보낸곳[방] = 대화


def 넘김에실었다(방: str) -> None:
    """넘김 파일에 설명서를 실어 보냈다 — 이어받는 새 대화에는 또 얹지 않는다."""
    if 방:
        _보낸곳[방] = _넘김표


def 새대화로이어붙임(방: str, 새대화: str) -> None:
    """꽉 찬 대화를 넘겨받아 방이 새 대화를 갖게 됐다. 넘김에 실었던 것이면 그 새 대화에 보낸 것으로 친다."""
    if _보낸곳.get(방) == _넘김표:
        _보낸곳[방] = 새대화 or ""


def 첫읽기얹기(답: dict, 도구이름: str, 이름키: str = "나물") -> dict:
    """이 대화에서 설명서를 아직 안 보냈으면 도구 결과 맨 앞(됨·이름 바로 뒤)에 얹어 돌려준다."""
    if not isinstance(답, dict) or "먼저읽기" in 답:
        return 답
    방, 대화 = _지금대화()
    if not 방 or 보냈나(방, 대화):
        return 답
    글 = 설명서글()
    if not 글:
        return 답                # 설명서 파일이 없으면 보낼 것이 없다(표시도 안 한다)
    보냈다고적기(방, 대화)
    안내 = ("이 대화에서 처음 오는 규칙입니다(한 번만 옵니다). 이 결과보다 먼저 아래 '설명서' 를 끝까지 읽고 따르세요 — "
            "쉬운 우리말, 하는 일 한두 문장으로 말하기, 모르면 【물음】 으로 묻기, 계획 → 승인 → 구현.")
    규칙안내 = 프로젝트규칙안내(프로젝트규칙())
    if 규칙안내:
        안내 += " " + 규칙안내
    새 = {}
    앞 = 2
    for 번, (키, 값) in enumerate(답.items()):
        if 번 == 앞 and "먼저읽기" not in 새:
            새["먼저읽기"] = 안내
            새["설명서"] = 글
        새[키] = 값
    if "먼저읽기" not in 새:
        새["먼저읽기"] = 안내
        새["설명서"] = 글
    return 새


def 숙주용() -> dict:
    """숙주와 넘김 파일에 실을 것."""
    목록 = 프로젝트규칙()
    return {
        "설명서": 설명서글(),
        "프로젝트규칙": 목록,
        "프로젝트규칙안내": 프로젝트규칙안내(목록),
    }
