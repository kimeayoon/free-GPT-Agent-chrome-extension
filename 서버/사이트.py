# -*- coding: utf-8 -*-
"""사이트 — 이 서버에 말을 걸 수 있는 곳을 가린다.

예전에는 요청을 보낸 곳(Origin)을 그대로 허용했다. 그러면 형님이 다른 탭에 열어 둔
아무 웹사이트나 127.0.0.1:8765 로 도구를 부를 수 있었다(자동 모드면 명령 실행까지).

지금은 이렇게 가른다.
  ① 출처가 없는 요청(curl · 파이썬 · 시험)      : 이 컴퓨터 안의 프로그램이라 그대로 받는다
  ② 확장(chrome-extension:// · moz-extension://) : 처음 말을 건 확장 하나를 믿고(처음 본 것을 믿기),
                                                    그 뒤 낯선 확장은 웹사이트처럼 승인을 받는다
  ③ 웹사이트(http · https)                      : 판에 "허용할까요?" 카드가 뜨고, 승인해야만 들어온다
        · 읽기만 허용 : 읽는 도구만(보기 등급)      · 전부 허용 : 지금 등급을 따른다
        · 허락한 사이트도 쓸 수 있는 길은 /ping(요약)과 /tool 뿐 — 방·폴더·등급·허락을 바꾸는
          길은 확장만 쓴다(사이트가 제 허락을 스스로 눌러 주면 안 되므로)
        · 'null' 출처(샌드박스 iframe · file://)는 승인 카드도 없이 막는다
  ④ Host 이름이 127.0.0.1 · localhost 가 아니면 막는다(DNS 리바인딩)
"""

import json
import re
import threading
import time
from pathlib import Path

import 안전파일

파일 = Path(__file__).with_name("허용사이트.json")
_자물쇠 = threading.RLock()

대기최대 = 20             # 승인을 기다리는 곳이 이보다 많아지면 오래된 것부터 버린다
대기분 = 30               # 이 시간이 지나도록 아무도 안 눌렀으면 잊는다
등급들 = ("보기", "전부")  # 사이트가 가질 수 있는 등급(보기 = 읽는 도구만, 전부 = 지금 등급을 따름)

웹모양 = re.compile(r"^https?://[A-Za-z0-9.\-]+(:\d{1,5})?$|^https?://\[[0-9A-Fa-f:]+\](:\d{1,5})?$")
확장모양 = re.compile(r"^(chrome|moz)-extension://[A-Za-z0-9\-]{8,64}$")

_대기 = {}                # 출처 → {"처음", "마지막", "횟수"}


def _읽기() -> dict:
    값 = 안전파일.json읽기(파일, {}, dict)
    값.setdefault("허용", {})      # 출처 → {"등급", "때"}
    값.setdefault("거부", [])
    값.setdefault("확장", [])      # 믿는 확장 출처
    return 값


def _쓰기(값: dict) -> None:
    안전파일.json쓰기(파일, 값)


def _지금글() -> str:
    return time.strftime("%Y-%m-%d %H:%M")


def 정규(출처: str) -> str:
    return (출처 or "").strip().rstrip("/").lower()


def 허용호스트(포트: int) -> set:
    return {f"127.0.0.1:{포트}", f"localhost:{포트}", f"[::1]:{포트}", "127.0.0.1", "localhost"}


def _대기정리() -> None:
    한계 = time.time() - 대기분 * 60
    for 키 in [k for k, v in _대기.items() if v["마지막"] < 한계]:
        del _대기[키]
    while len(_대기) > 대기최대:
        del _대기[min(_대기, key=lambda k: _대기[k]["마지막"])]


def _대기에적기(출처: str) -> None:
    지금 = time.time()
    칸 = _대기.setdefault(출처, {"처음": 지금, "마지막": 지금, "횟수": 0})
    칸["마지막"] = 지금
    칸["횟수"] += 1
    _대기정리()


def 판정(오리진) -> dict:
    """요청의 Origin 하나를 보고 받을지 가린다.

    돌려주는 것: 종류(없음·확장·웹·모름) · 허용 · 등급 · 대기 · 출처 · 이유
    """
    if 오리진 is None or str(오리진).strip() == "":
        return {"종류": "없음", "허용": True, "등급": "전부", "대기": False, "출처": "", "이유": ""}
    출처 = 정규(오리진)
    if 출처 == "null" or not (웹모양.match(출처) or 확장모양.match(출처)):
        # 모양이 이상하거나 'null' — 승인 카드도 없이 막는다(아무나 만들 수 있는 출처라 허락해도 뜻이 없다)
        return {"종류": "모름", "허용": False, "등급": "", "대기": False, "출처": 출처,
                "이유": "출처를 알 수 없는 요청입니다(샌드박스 페이지 · file:// 등)."}

    with _자물쇠:
        기록 = _읽기()
        if 확장모양.match(출처):
            if 출처 in 기록["확장"]:
                return {"종류": "확장", "허용": True, "등급": "전부", "대기": False, "출처": 출처, "이유": ""}
            if not 기록["확장"]:
                # 처음 말을 건 확장을 믿는다. 웹 페이지는 확장 출처를 흉내 낼 수 없다(브라우저가 붙인다).
                기록["확장"].append(출처)
                _쓰기(기록)
                return {"종류": "확장", "허용": True, "등급": "전부", "대기": False, "출처": 출처, "이유": ""}
            # 낯선 확장 — 웹사이트처럼 승인을 받는다
        if 출처 in 기록["거부"]:
            return {"종류": "웹", "허용": False, "등급": "", "대기": False, "출처": 출처,
                    "이유": "사용자가 이 곳을 거부했습니다."}
        허락 = 기록["허용"].get(출처)
        if 허락:
            return {"종류": "웹", "허용": True, "등급": 허락.get("등급", "보기"), "대기": False, "출처": 출처, "이유": ""}
        _대기에적기(출처)
        return {"종류": "웹", "허용": False, "등급": "", "대기": True, "출처": 출처,
                "이유": "아직 허용되지 않은 곳입니다. 에이전트 판에 뜬 '웹사이트 허용' 카드에서 사용자가 허용해야 합니다."}


def 요약() -> dict:
    with _자물쇠:
        _대기정리()
        기록 = _읽기()
        지금 = time.time()
        return {
            "대기": sorted(
                [{"출처": 출처, "횟수": 칸["횟수"], "몇초전": int(지금 - 칸["처음"]),
                  "종류": "확장" if 확장모양.match(출처) else "웹"} for 출처, 칸 in _대기.items()],
                key=lambda x: x["몇초전"]),
            "허용": [{"출처": 출처, "등급": 값.get("등급", "보기"), "때": 값.get("때", "")}
                   for 출처, 값 in 기록["허용"].items()],
            "거부": list(기록["거부"]),
            "확장": list(기록["확장"]),
        }


def 허용하기(출처: str, 등급: str = "보기") -> dict:
    출처 = 정규(출처)
    if not (웹모양.match(출처) or 확장모양.match(출처)):
        raise ValueError(f"허용할 수 없는 출처 모양입니다: {출처}")
    if 등급 not in 등급들:
        raise ValueError("등급은 보기(읽기만) 또는 전부 입니다.")
    with _자물쇠:
        기록 = _읽기()
        기록["허용"][출처] = {"등급": 등급, "때": _지금글()}
        기록["거부"] = [x for x in 기록["거부"] if x != 출처]
        _쓰기(기록)
        _대기.pop(출처, None)
    return 요약()


def 거부하기(출처: str) -> dict:
    출처 = 정규(출처)
    with _자물쇠:
        기록 = _읽기()
        if 출처 not in 기록["거부"]:
            기록["거부"].append(출처)
        기록["허용"].pop(출처, None)
        _쓰기(기록)
        _대기.pop(출처, None)
    return 요약()


def 지우기(출처: str) -> dict:
    """허용했거나 거부한 것을 목록에서 뺀다(다시 오면 처음처럼 물어본다)."""
    출처 = 정규(출처)
    with _자물쇠:
        기록 = _읽기()
        기록["허용"].pop(출처, None)
        기록["거부"] = [x for x in 기록["거부"] if x != 출처]
        if 출처 in 기록["확장"] and len(기록["확장"]) > 1:
            기록["확장"] = [x for x in 기록["확장"] if x != 출처]
        _쓰기(기록)
        _대기.pop(출처, None)
    return 요약()
