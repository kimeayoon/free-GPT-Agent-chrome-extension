# -*- coding: utf-8 -*-
"""길잡이 — 다음에 무엇을 하면 좋은지 한 줄로 알려준다.

막지 않는다. 하려는 일은 그대로 하게 두고, 결과에 '귀띔' 한 줄을 얹는다.
하네스는 벽이 아니라 옆에서 알려주는 사람이다.

왜 필요한가:
  대화창은 언제든 꽉 찬다. 꽉 차면 무엇을 왜 했는지가 통째로 사라진다.
  차례와 기억은 방 폴더에 남아 숙주로 그대로 넘어가므로, 그것만 챙겨 두면
  다음 대화에서 헤매지 않는다. 그래서 자꾸 적어 두라고 옆에서 일러 준다.

한 번에 한 마디만 한다. 여러 줄을 한꺼번에 얹으면 아무도 안 읽는다.
"""

import time

import rooms
import tools_plan

# 무언가를 바꾸거나 돌리는 나물
손대는나물 = {
    "부추", "상추", "냉이", "시금치", "갓", "쑥",
    "도라지", "두릅", "칡", "열매",
}

# 파일 내용을 바꾸는 나물 (바꿨으면 확인해야 한다)
바꾸는나물 = {"부추", "상추", "갓", "쑥", "시금치"}

가장짧은일 = 8
가장적은차례 = 2

# 차례를 세워 놓고 손대는 도구를 이만큼 쓰는 동안 한 번도 안 고치면 한마디 한다.
# (계획 0/6 인 채로 도구를 60번 넘게 써서 판의 할 일이 하루 내내 멈춰 있었다)
묵은차례마다 = 12
_차례묵은수: dict = {}     # 방(차례 파일)마다 — 서버를 다시 켜면 0 부터 센다

# ── 쓸 수 있는 도구를 권한다 ──
# GPT 는 지침에 있는 일꾼(콩)·예약(배추)을 한 번도 안 불렀다. 발로란트 방 기록 274번 중
# 열무 75 · 고사리 68 · 부추 48 · 도라지 43, 콩 0 · 배추 4. 돌고 있는 일을 고사리로 68번 직접
# 들여다봤다. 쓸 수 있다는 것만 알고 '언제' 쓸지를 몰라서다. 그래서 그 순간에 한 줄 권한다.
# 막지 않는다. 같은 권유는 연속으로 이만큼 쌓였을 때만, 그 뒤로도 이만큼마다만 한다.
연속읽기권유 = 4
연속들여다보기권유 = 3

# ── 말 없이 도구만 이어 부르면 한마디 하라고 일러 준다 ──
# 사용자는 도구만 오가는 동안 지금 무슨 일을 하는지 알 수 없다(설명서 라). 말이 필요 없는 짧은 반복도 있으니
# 막지 않고, 말 없이 이만큼 이어졌을 때 한 번, 그 뒤로도 이만큼 더 이어질 때마다 한 번만 일러 준다.
말없이도구권유 = 8
말없이도구간격 = 12
_말알림수: dict = {}       # 방마다 — 마지막으로 일러 준 때의 '말 없는 도구' 수

# ── 오류가 이어지면 짐작하지 말고 웹 검색으로 확인하라고 일러 준다 ──
# 인터넷은 ChatGPT 자체 웹 검색이 있다(서버가 대신 검색하지 않는다). 도라지가 연달아 실패하면 한 번, 그 뒤로도 이만큼마다 한 번.
검색권유실패수 = 2
검색권유간격 = 3
_도라지실패: dict = {}     # 방마다 — 연달아 실패한 도라지 수
_연속: dict = {}           # 방마다 {"나물": 이름, "수": 몇 번째 연속}


def _연속세기(나물이름: str) -> int:
    """같은 도구를 이어서 몇 번째 부르는지. 다른 도구를 부르면 다시 센다."""
    열쇠 = _방열쇠()
    앞 = _연속.get(열쇠) or {}
    수 = (앞.get("수", 0) + 1) if 앞.get("나물") == 나물이름 else 1
    _연속[열쇠] = {"나물": 나물이름, "수": 수}
    return 수


def _권유(나물이름: str) -> str:
    """연속으로 같은 도구를 쓰는 때에 맞는 권유 한 줄. 없으면 빈 글."""
    수 = _연속세기(나물이름)
    if 나물이름 == "열무" and 수 % 연속읽기권유 == 0:
        return (f"파일을 이어서 {수}번 읽고 있습니다. 서로 다른 파일·주제를 조사하는 것이면 "
                "갈래마다 콩(역할 분석) 일꾼을 한 명씩 불러 나눠 맡길 수 있습니다(한 답에 여러 명, 동시에 12명까지). 그동안 다른 일을 이어 가고, "
                "결과는 파일로 옵니다. 한 답에 열무를 몰아 담는 것도 방법입니다.")
    if 나물이름 == "고사리" and 수 % 연속들여다보기권유 == 0:
        return (f"돌고 있는 일을 {수}번째 들여다보고 있습니다. 끝나면 알려 주는 예약이 있습니다 — "
                "배추 조건 뒤뜰끝:번호 / 말 결과를 고사리로 확인하고 보고. "
                "예약을 걸고 답을 끝내면 되고, 그동안 같은 걸 되풀이해 보지 않아도 됩니다.")
    return ""


def _말권유() -> str:
    try:
        방 = (rooms.지금방() or {}).get("쪽번호", "")
        수 = rooms.말없는도구수(방)
    except Exception:
        return ""
    마지막 = _말알림수.get(방, -1)
    if 수 < 마지막:                 # 그 사이 말을 했다 — 다시 센다
        마지막 = -1
        _말알림수.pop(방, None)
    if 수 < 말없이도구권유 or (마지막 >= 0 and 수 - 마지막 < 말없이도구간격):
        return ""
    _말알림수[방] = 수
    return (f"말 없이 도구만 {수}번 이어졌습니다. 사용자는 지금 무엇을 왜 하는지 모릅니다 — 다음 바구니의 나물 줄 바로 아래에 "
            "`하는말 평가 파일에서 26차원 코드를 찾는 중이에요` 처럼 한두 문장을 적어 주세요. "
            "바구니 앞에 쓴 글은 생각이 끝나면 화면에서 지워져 사용자가 못 봅니다. "
            "같은 파일을 이어 읽는 짧은 반복이면 말하지 않아도 됩니다(설명서 라).")


def _검색권유(나물이름: str, 결과) -> str:
    if 나물이름 != "도라지" or not isinstance(결과, dict):
        return ""
    열쇠 = _방열쇠()
    if 결과.get("ok") is not False:
        _도라지실패[열쇠] = 0 if 결과.get("ok") else _도라지실패.get(열쇠, 0)
        return ""
    수 = _도라지실패.get(열쇠, 0) + 1
    _도라지실패[열쇠] = 수
    if 수 >= 검색권유실패수 and (수 - 검색권유실패수) % 검색권유간격 == 0:
        return (f"돌려보기가 {수}번 연달아 실패했습니다. 같은 방법을 되풀이하거나 짐작하지 말고, 오류 메시지의 핵심 낱말로 "
                "ChatGPT 웹 검색을 해서 원인을 확인하세요(바구니 없는 답으로 검색하고, 근거 주소를 한 줄 남기세요 — 설명서 바).")
    return ""


def _차례보기() -> dict:
    try:
        return tools_plan.plan_get()
    except Exception:
        return {"task": None, "steps": []}


def _방열쇠() -> str:
    try:
        return str(tools_plan._계획파일())
    except Exception:
        return ""


def _건너뛴단계(단계들: list) -> list:
    """가장 뒤에 손댄 단계보다 앞인데 아직 기다림·하는중인 단계 번호들."""
    손댄 = [번 for 번, s in enumerate(단계들, 1) if s.get("status") != "기다림"]
    if not 손댄:
        return []
    return [번 for 번, s in enumerate(단계들[:손댄[-1] - 1], 1)
            if s.get("status") in ("기다림", "하는중")]


def _차례갱신귀띔() -> str:
    """고구마 뒤 — 앞 단계를 표시 없이 건너뛰었으면 알려 준다."""
    빠진 = _건너뛴단계(_차례보기().get("steps") or [])
    if not 빠진:
        return ""
    번호들 = ", ".join(str(번) for 번 in 빠진)
    return (f"앞 차례 {번호들}번이 끝으로 표시되지 않았습니다. 실제로 끝냈으면 "
            f"고구마 몇 {빠진[0]} / 상태 끝, 하지 않았으면 상태 건너뜀 으로 하나씩 "
            "표시하세요. 한 답에 고구마 바구니를 여러 개 넣어도 됩니다.")


def 두릅안내(번호: str) -> str:
    """두릅으로 일을 풀어놓은 직후에 GPT 에게 현황판 쓰는 법을 한 번 가르친다."""
    줄바꿈 = chr(10)
    예 = 줄바꿈.join([
        "나물 당근", "이름 학습", "항목《",
        f"일 {번호}", "진행 logs▸학습.log / 낱말 update",
        "숫자 logs▸학습.log / 낱말 loss", "파일 checkpoints", "기계 GPU", "》",
    ])
    return (
        "이 일은 사용자 판에 저절로 뜹니다(진행률·경과·숫자는 서버가 직접 읽습니다). "
        "더 보여 줄 것이 있으면 무엇이 좋을지 생각해서 당근으로 거세요. 예)" + 줄바꿈 + 예 + 줄바꿈 +
        "항목은 한 줄에 하나, 고를 수 있는 종류는 일·진행·숫자·기록·파일·값·기계. "
        "지금 값은 나물 당근 / 짓 보기. 끝나기를 기다려 알려 주는 것은 배추 조건 예약입니다. "
        "판에는 이름이 작은 네모 칸으로 보이니, 이름(위 예의 '학습')은 쉬운 우리말로 짧게 지으세요. "
        "숫자 항목의 낱말(loss 같은 영어 이름)은 로그에 찍힌 그대로 쓰되 판이 우리말로 바꿔 보여 줍니다.")


# ── 말씨 ──
# 설명서(쉬운 우리말·한두 문장으로 하는 일 말하기)는 새 대화부터 읽는다. 이미 길어진 대화는 읽은 지 오래라 잊는다.
# 그래서 도구 결과에 이만큼 시간마다 한 줄 되새겨 준다(처음 부른 때부터 센다 — 막 시작한 일에는 안 한다).
말씨알림초 = 600
_말씨때: dict = {}         # 방마다 — 마지막으로 되새겨 준 때(없으면 처음 부른 때)
말씨글 = ("말씨: 사용자에게 하는 말은 쉬운 우리말로 쓰세요. 어려운 영어·전문 낱말은 풀어 쓰고, "
          "하는 일은 바구니 안 `하는말` 줄에 한두 문장으로 적어 주세요(설명서 라).")


def _지금초() -> float:
    return time.time()


def 귀띔(나물이름: str, 결과) -> str:
    """이 도구를 쓴 뒤에 해 주면 좋은 말 한 마디. 할 말이 없으면 빈 글. 가끔 말씨를 되새겨 준다."""
    말 = _귀띔본체(나물이름, 결과)
    try:
        방 = (rooms.지금방() or {}).get("쪽번호", "")
    except Exception:
        방 = ""
    지금 = _지금초()
    앞 = _말씨때.get(방)
    if 앞 is None:
        _말씨때[방] = 지금
    elif 지금 - 앞 >= 말씨알림초:
        _말씨때[방] = 지금
        return (말 + " / " if 말 else "") + 말씨글
    return 말


def _귀띔본체(나물이름: str, 결과) -> str:
    """이 도구를 쓴 뒤에 해 주면 좋은 말 한 마디. 할 말이 없으면 빈 글."""

    권유 = _권유(나물이름)       # 어떤 도구든 지나가며 연속을 센다

    # 사용자가 판에서 목표를 고쳤으면 무엇보다 먼저 알린다 — 모르고 감자로 덮어쓰면 고친 것이 사라진다
    try:
        고침 = tools_plan.사용자고침알림가져오기()
    except Exception:
        고침 = []
    if 고침:
        return ("사용자가 판에서 목표를 고쳤습니다: " + " / ".join(고침) + ". 이 모양을 기준으로 이어 가세요 — "
                "감자로 새로 덮어쓰지 마세요(토란으로 지금 모양을 볼 수 있습니다).")

    # 방금 답에 확실하지 않은 말이 있었으면 짐작으로 이어 가지 말고 물어보라고 한 번 일러 준다
    try:
        방 = (rooms.지금방() or {}).get("쪽번호", "")
        단서 = rooms.불확실한말.pop(방, "") if 방 else ""
    except Exception:
        단서 = ""
    if 단서:
        return (f"방금 답에 확실하지 않은 말이 있었습니다('{단서}'). 짐작으로 이어 가지 말고 사용자에게 물어보세요 — "
                "바구니 없이 답 끝에 【물음】 카드(선택지 둘에서 넷, 각각 '그러면 어떻게 되는지' 한 줄). "
                "파일을 열어 알 수 있는 것은 먼저 열무로 확인하세요(설명서 마).")

    if 나물이름 in ("감자", "고구마"):
        _차례묵은수[_방열쇠()] = 0
        if 나물이름 == "감자" and isinstance(결과, dict) and 결과.get("앞목표"):
            앞 = 결과["앞목표"]
            return (f"앞 목표 '{앞['일']}'({앞['진도']})는 지난 목표로 보관했습니다(번호 {앞['번호']}). "
                    "같은 목표를 이어 가는 것이면 새로 세우지 말고 고구마로 고치세요: "
                    "짓 더하기 · 빼기 · 고치기 · 옮기기 · 목표고치기. 되살리기는 짓 되살리기 / 번호 … 입니다. "
                    "목표를 접거나 갈아엎는 것은 먼저 사용자 승인을 받으세요(설명서 가-2).")
        return _차례갱신귀띔() if 나물이름 == "고구마" else ""

    if 권유:
        return 권유

    말 = _말권유()
    if 말:
        return 말

    if 나물이름 not in 손대는나물:
        return ""

    # 뒤뜰에 일을 풀어놓았으면 현황판을 걸 수 있다고 알려 준다. 차례 귀띔보다 먼저 —
    # 두릅은 드문 일이라 이 순간에만 가르칠 수 있다(지침 8000자 한도에 설명을 못 넣는다).
    if 나물이름 == "두릅" and isinstance(결과, dict) and 결과.get("번호"):
        return 두릅안내(결과["번호"])

    차례 = _차례보기()
    일 = (차례.get("task") or "").strip()
    단계들 = 차례.get("steps") or []
    남은것 = [s for s in 단계들 if s.get("status") not in ("끝", "건너뜀")]

    # ① 차례를 오래 안 고쳤으면 다른 말보다 먼저 한다(다른 귀띔에 묻혀 계속 무시됐다)
    if 일 and 남은것:
        열쇠 = _방열쇠()
        묵은수 = _차례묵은수.get(열쇠, 0) + 1
        _차례묵은수[열쇠] = 묵은수
        if 묵은수 % 묵은차례마다 == 0:
            return (f"차례를 도구 {묵은수}번째 고치지 않았습니다(사용자 화면의 할 일이 "
                    f"{차례.get('progress')} 에 멈춰 있습니다). 끝낸 단계는 고구마로 "
                    "상태 끝, 지금 하는 단계는 상태 하는중 으로 맞춰 주세요.")

    # ①-2 돌려보기가 연달아 실패하면 짐작하지 말고 웹 검색으로 확인하라고 한다(차례 귀띔의 횟수 세기를 가리지 않게 ① 뒤에)
    검색 = _검색권유(나물이름, 결과)
    if 검색:
        return 검색

    # ② 무엇을 하는 중인지 적혀 있지 않으면 적어 두라고 한다
    if not 일 or not 단계들:
        return ("무엇을 왜 하는지 감자로 적어 두면 좋습니다. 대화창이 꽉 차면 "
                "여기 적어둔 것만 남습니다. 예) 나물 감자 / 일 전투 시뮬레이터에 "
                "벽 충돌 넣기 / 차례《 자료 구조 정하기 / 충돌 계산 / 시험 쓰기 / 확인 》")

    if len(일) < 가장짧은일 or len(단계들) < 가장적은차례:
        return (f"적어둔 것이 너무 성깁니다(일 {len(일)}자, 차례 {len(단계들)}개). "
                "나중에 보고 알아볼 만큼 적어 두면 좋습니다.")

    if not 남은것:
        return (f"'{일}' 은(는) 다 끝났다고 적혀 있습니다. 새 일을 하는 중이면 "
                "감자로 다시 세우고, 정말 끝났으면 우엉으로 알아낸 것을 적어 두세요.")

    # ③ 바꿨으면 확인하라고 한다
    if 나물이름 in 바꾸는나물 and isinstance(결과, dict) and 결과.get("success", True):
        return "바꿨으면 도라지로 확인하고 나서 끝내세요. 확인 전에는 고쳤다고 하지 마세요."

    # ④ 한 단계 끝냈으면 표시해 두라고 한다
    if 나물이름 == "도라지" and isinstance(결과, dict) and 결과.get("ok"):
        하는중 = [s for s in 단계들 if s.get("status") == "하는중"]
        if 하는중:
            몇 = 단계들.index(하는중[0]) + 1
            return (f"확인이 통과했습니다. 지금 차례 {몇}번 '{하는중[0].get('name')}' "
                    f"이 끝났으면 고구마로 표시해 두세요. 예) 나물 고구마 / 몇 {몇} / 상태 끝")

    # ⑤ 이름은 대화 제목에서 저절로 붙는다. 그래도 안 붙은 때만 맨 뒤에서 말한다.
    try:
        if rooms.이름필요한가() and 나물이름 != "이름표":
            return ("이 방에 아직 이름이 없습니다. 대화 제목이 정해지면 저절로 붙지만, "
                    "안 붙으면 이름표로 지어 주세요.")
    except Exception:
        pass

    return ""
