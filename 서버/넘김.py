# -*- coding: utf-8 -*-
"""넘김 — ChatGPT 대화가 꽉 찼을 때 새 대화가 이어받을 자료를 파일 한 장으로 만든다.

확장이 같은 프로젝트에 새 대화를 열고 이 글을 넘김_<때>.txt 로 첨부한다.
새 대화도 같은 방으로 이어지므로 판의 기록·할 일·기억은 그대로다.

담는 것 (중요한 것부터 — 긴 파일은 GPT 가 앞부분을 더 잘 본다):
  1 할 일(목표와 차례, 쪽지 전부)  2 기억  3 최근 손댄 파일  4 남은 일
  5 마지막 도구 결과  6 대화 전체
"""

import json
from datetime import datetime

최근대화수 = 40          # 압축 요약이 없을 때 넣는 최근 기록 수
압축뒤최대 = 80          # 압축 요약 뒤 기록도 이만큼까지만

import rooms
import tools_plan
import tools_resume
import tools_timer
import 설명서

_선 = "━" * 24


def _대화줄(항목: dict) -> str:
    때 = 항목.get("때", "")
    종류 = 항목.get("종류")
    글 = (항목.get("글") or "").rstrip()
    if 종류 == "사용자":
        return f"[{때}] 사용자:\n{글}"
    if 종류 == "gpt":
        return f"[{때}] GPT:\n{글}"
    if 종류 == "예약":
        return f"[{때}] 에이전트(예약 알림):\n{글}"
    if 종류 == "도구":
        try:
            값 = json.loads(글)
        except ValueError:
            값 = {}
        결과 = "성공" if 값.get("성공") else "실패"
        꼬리 = f" {값['꼬리']}" if 값.get("꼬리") else ""
        return f"[{때}] 도구: {값.get('이름', '')}({값.get('나물', '')}) {값.get('대상', '')} → {결과}{꼬리}"
    return ""          # '나'(소쿠리 원문)·'요약' 은 도구 줄이 대신한다


def 넘김글(쪽번호: str) -> str:
    설정 = rooms.읽기()
    방 = next((r for r in 설정["방들"] if r["쪽번호"] == 쪽번호), None)
    if 방 is None:
        raise ValueError("그런 방이 없습니다.")

    rooms.방고정(쪽번호)
    try:
        이어 = tools_resume.resume(_표시=False)
        계획 = tools_plan.plan_get(전체=True)
    finally:
        rooms.방풀기()
    설명서.넘김에실었다(쪽번호)          # 이어받는 새 대화에는 첫 도구 결과에 또 얹지 않는다
    대화 = rooms.대화읽기(쪽번호, 최대=0)
    압축, _ = rooms.압축읽기(쪽번호)
    # 압축 요약이 있으면 그 뒤 기록만, 없으면 최근 것만. 통째로 넘기면 새 대화도 금방 느려진다.
    뒤기록, 앞뺀수 = rooms.압축뒤기록(쪽번호) if 압축 else (대화, 0)
    한도 = 압축뒤최대 if 압축 else 최근대화수
    뺀수 = max(0, len(뒤기록) - 한도) + 앞뺀수
    뒤기록 = 뒤기록[-한도:]
    차례번호 = len(방.get("대화들") or []) + 2
    새이름 = f"{방.get('기본이름') or 방.get('이름') or '대화'} {차례번호}번"

    남은것 = [f"- {i}. {s['name']} ({s['status']})"
             for i, s in enumerate(계획.get("steps") or [], 1)
             if s.get("status") not in ("끝", "건너뜀")]
    마지막결과 = next((h.get("글", "") for h in reversed(대화) if h.get("종류") == "나"), "")
    # 접거나 갈아엎은 앞 목표 — 새 대화가 같은 일을 다시 세우지 않게 최근 셋만 알린다
    rooms.방고정(쪽번호)
    try:
        지난 = tools_plan.판정보()["지난목표"][:3]
    finally:
        rooms.방풀기()
    지난목표줄들 = (["", "지난 목표(되살리기 번호는 나물 고구마 / 짓 되살리기 / 번호 …):"]
                + [f"- {x['번호']} '{x.get('일')}' {x.get('진도')} · {x.get('까닭')}"
                   + (f" ({x['이유']})" if x.get("이유") else "") + f" · {x.get('끝낸때')}" for x in 지난]) if 지난 else []
    최근 = "\n".join(f"- {x['밭']} ({x['마지막손댐']})" for x in 이어.get("최근손댐") or [])
    대화줄들 = [줄 for 줄 in (_대화줄(h) for h in 뒤기록) if 줄]

    try:
        지금상태 = tools_timer.지금상태글(쪽번호)
    except Exception:
        지금상태 = ""

    조각 = [
        "【넘김 파일】 로컬 에이전트가 만든 이어받기 자료 (사용자 행동 아님)",
        f"만든 때: {datetime.now().strftime('%Y-%m-%d %H:%M')}",
        f"방: {방.get('이름') or '(이름 없음)'}",
        f"일할 폴더: {방.get('밭') or '(아직 없음)'}",
        f"이 대화: {새이름} (앞 대화 {차례번호 - 1}개)",
        "",
        "새 GPT 에게: 앞 대화가 꽉 차거나 느려져 이 대화로 옮겨 왔습니다. 이 파일을 끝까지 읽고",
        "먼저 【압축】 … 【압축끝】 로 아래 틀의 압축 요약을 쓴 뒤, 사용자에게 다시 묻지 말고",
        "'남은 일' 부터 이어서 하세요. 규칙(지침)은 그대로입니다.",
        "이어서 한다는 것은 압축 요약을 쓴 바로 그 답 안에 다음 바구니를 쓰는 것입니다. 결과는 저절로 오지 않고,",
        "누가 보내 주지도 않습니다. '결과가 오면 이어서' 로 답을 끝내지 마세요(에이전트는 연결돼 있습니다).",
        "  압축 틀: 1 사용자가 원하는 것 · 2 정한 규칙과 결정 · 3 파일과 코드(자리·무엇·왜)",
        "           4 오류와 해결 · 5 끝낸 것 · 6 남은 일 · 7 지금 하던 일과 바로 다음 단계",
        "  앞 압축 요약이 있으면 그것을 고쳐 새로 쓰세요(합치기). 사실만, 짐작 금지.",
        "",
        "목차: 설명서 · 0 앞 압축 요약 · 1 할 일 · 2 기억 · 3 최근 손댄 파일 · 4 남은 일 · 5 마지막 도구 결과 · 5-1 지금 상태 · 6 최근 대화",
        "",
        # 사용자가 정한 규칙을 맨 위에. 새 대화는 숙주를 안 부르므로 여기서 받아야 한다
        f"{_선} 설명서 (사용자가 정한 규칙 — 먼저 읽고 끝까지 따르세요) {_선}",
        (이어.get("설명서") or "(설명서 파일이 없습니다)").rstrip(),
        *([이어["프로젝트규칙"]] if 이어.get("프로젝트규칙") else []),
        "",
        f"{_선} 0. 앞 압축 요약 {_선}",
        압축.rstrip() or "(아직 없음 — 이번에 처음 쓰세요)",
        "",
        f"{_선} 1. 할 일 {_선}",
        f"목표: {계획.get('task') or '(없음)'}   진도: {계획.get('progress', '')}",
        계획.get("board") or "(계획 없음)",
        *지난목표줄들,
        "",
        f"{_선} 2. 기억 {_선}",
        (이어.get("content") or "(적어둔 기억 없음)").rstrip(),
        "",
        f"{_선} 3. 최근 손댄 파일 {_선}",
        최근 or "(없음)",
        "",
        f"{_선} 4. 남은 일 {_선}",
        "\n".join(남은것) or "(차례상 남은 일 없음 — 대화 끝부분에서 사용자의 마지막 요청을 확인하세요)",
        "",
        f"{_선} 5. 마지막 도구 결과 {_선}",
        마지막결과.rstrip() or "(없음)",
        "",
        f"{_선} 5-1. 지금 상태 — 위 5번은 그때 것이고, 이것이 넘기는 지금 서버가 잰 것입니다 {_선}",
        지금상태 or "(최근 하루 동안 돈 뒤뜰 일이나 예약이 없습니다)",
        "",
        f"{_선} 6. 최근 대화 ({len(대화줄들)}개, 오래된 것부터. 앞의 {뺀수}개는 압축 요약·할 일·기억이 대신함) {_선}",
        "\n\n".join(대화줄들) or "(없음)",
        "",
    ]
    return "\n".join(조각)
