# -*- coding: utf-8 -*-
"""눈(화면 보기)과 손(키보드·마우스)을 쓰기 전에 사용자에게 승인받는 문.

GPT 가 오이(눈)·마늘(손)을 부르면, 허가가 없으면 아무것도 하지 않고 '기다림' 요청만 남긴다.
사용자가 판의 카드에서 [허용] 을 눌러야 허가가 생기고, 허가는 창 하나 + 정해진 시간 동안만 간다.
허가는 메모리에만 있다 — 서버를 껐다 켜면 모두 사라진다.

  창   : 제목에 이 글이 든 창에만 쓸 수 있다. '*' 는 화면 전체(모든 창).
  시간 : 기본 10분, 최대 30분(손으로 화면 전체를 다룰 때는 5분).
"""

import itertools
import threading
import time

종류들 = ("눈", "손")
기본분 = 10
최대분 = 30
손전체최대분 = 5
창최대글자 = 60

_잠금 = threading.RLock()
기다림: dict = {}          # 열쇠 → 요청(판에 카드로 뜬다)
허가들: dict = {}          # 번호 → 허가
_번호 = itertools.count(1)
_지금 = time.time          # 시험에서 바꿔 끼운다


def 창다듬기(창) -> str:
    글 = str(창 or "").strip()
    return "*" if 글 in ("", "*", "전체", "화면", "화면전체") else 글[:창최대글자]


def _분(종류: str, 창: str, 분) -> int:
    try:
        값 = int(float(분)) if str(분 or "").strip() else 기본분
    except ValueError:
        raise ValueError('"분" 은 숫자여야 합니다(1~30).')
    한도 = 손전체최대분 if (종류 == "손" and 창 == "*") else 최대분
    return max(1, min(값, 한도))


def _만료정리():
    지금 = _지금()
    for 번호 in [n for n, h in 허가들.items() if h["끝"] <= 지금]:
        허가들.pop(번호, None)


def 덮나(허가: dict, 제목) -> bool:
    """이 허가가 그 창(제목)에 쓰이나. 제목이 None 이면 화면 전체를 다루는 일이다."""
    if 허가["창"] == "*":
        return True
    return 제목 is not None and 허가["창"].lower() in str(제목).lower()


def 찾기(종류: str, 제목) -> dict | None:
    """그 창에 쓸 수 있는 살아 있는 허가(남은 시간이 가장 긴 것). 없으면 None."""
    with _잠금:
        _만료정리()
        맞는 = [h for h in 허가들.values() if h["종류"] == 종류 and 덮나(h, 제목)]
        return max(맞는, key=lambda h: h["끝"]) if 맞는 else None


def 있나(종류: str) -> bool:
    with _잠금:
        _만료정리()
        return any(h["종류"] == 종류 for h in 허가들.values())


def 쓰기(허가: dict) -> None:
    with _잠금:
        허가["쓴수"] = 허가.get("쓴수", 0) + 1


def 요청하기(종류: str, 창, 분, 이유: str) -> dict:
    """허가를 달라고 요청한다(카드를 띄운다). 아무것도 허락하지 않는다."""
    if 종류 not in 종류들:
        raise ValueError("종류는 눈 · 손 중 하나입니다.")
    창 = 창다듬기(창)
    분 = _분(종류, 창, 분)
    열쇠 = f"허가::{종류}::{창}"
    표시 = "화면 전체" if 창 == "*" else f"창 '{창}'"
    with _잠금:
        기다림[열쇠] = {
            "열쇠": 열쇠, "갈래": 종류, "무엇": 표시, "창": 창, "분": 분,
            "왜": (이유 or "").strip() or "(이유를 안 적었습니다)",
            "때": time.strftime("%H:%M:%S"),
        }
    하는일 = "화면을 보려" if 종류 == "눈" else "키보드와 마우스를 움직이려"
    return {
        "상태": "기다림", "종류": 종류, "창": 창, "분": 분,
        "안내": (f"아직 아무것도 하지 않았습니다. 사용자에게 이렇게 말하고 답변을 끝내세요 — "
                 f"'{표시}에서 {하는일} 합니다. 창에 뜬 물음에서 [허용] 을 눌러 주세요.' "
                 f"허락이 떨어지면 알림이 옵니다. 그때 다시 부르세요(허가는 {분}분 동안만 갑니다)."),
    }


def 기다림목록() -> list:
    with _잠금:
        return list(기다림.values())


def 허락하기(열쇠: str) -> dict:
    with _잠금:
        요청 = 기다림.pop(열쇠, None)
        if 요청 is None:
            raise ValueError("그런 요청이 없습니다(이미 처리했을 수 있습니다).")
        번호 = next(_번호)
        지금 = _지금()
        허가들[번호] = {
            "번호": 번호, "종류": 요청["갈래"], "창": 요청["창"], "분": 요청["분"],
            "시작": 지금, "끝": 지금 + 요청["분"] * 60, "왜": 요청["왜"], "쓴수": 0,
        }
    하는일 = "화면 보기" if 요청["갈래"] == "눈" else "키보드·마우스 쓰기"
    return {"열쇠": 열쇠, "갈래": 요청["갈래"], "무엇": 요청["무엇"], "됨": True, "끝번호": 0,
            "허가번호": 번호,
            "나온것": f"사용자가 {하는일}를 허락했습니다 — {요청['무엇']}, {요청['분']}분 동안. 이제 {'오이' if 요청['갈래'] == '눈' else '마늘'}을 다시 부르세요."}


def 거절하기(열쇠: str) -> dict:
    with _잠금:
        요청 = 기다림.pop(열쇠, None)
    return {"열쇠": 열쇠, "갈래": (요청 or {}).get("갈래", ""), "무엇": (요청 or {}).get("무엇", ""), "됨": False,
            "나온것": "사용자가 허락하지 않았습니다. 다시 요청하지 말고 사용자에게 무엇이 걱정인지 물어보세요."}


def 허가중목록() -> list:
    with _잠금:
        _만료정리()
        지금 = _지금()
        return [{"번호": h["번호"], "종류": h["종류"], "창": h["창"], "남은초": int(h["끝"] - 지금),
                 "쓴수": h.get("쓴수", 0), "왜": h["왜"]} for h in 허가들.values()]


def 그만(번호=None) -> int:
    """허가 하나(번호) 또는 전부(None)를 거둔다. 거둔 수."""
    with _잠금:
        if 번호 is None:
            수 = len(허가들)
            허가들.clear()
            return 수
        return 1 if 허가들.pop(int(번호), None) is not None else 0


def 모두비우기() -> None:
    """(시험용) 모든 기다림·허가를 지운다."""
    with _잠금:
        기다림.clear()
        허가들.clear()
