def _순번(등급: str) -> int:
    return 등급목록.index(등급)


def 등급읽기() -> str:
    값 = (안전파일.json읽기(등급파일, {}, dict) or {}).get("등급")
    return 값 if 값 in 등급목록 else 기본등급


def 등급쓰기(등급: str) -> str:
    if 등급 not in 등급목록:
        raise ValueError(f"등급은 {', '.join(등급목록)} 중 하나여야 합니다.")
    값 = dict(안전파일.json읽기(등급파일, {}, dict) or {})
    값["등급"] = 등급
    안전파일.json쓰기(등급파일, 값)
    return 등급


def 모드읽기() -> str:
    값 = 안전파일.json읽기(등급파일, {}, dict) or {}
    if 값.get("모드") in 모드목록:
        return 값["모드"]
    return 옛등급모드.get(값.get("등급"), 기본모드)


def 모드쓰기(모드: str) -> str:
    """모드를 바꾼다. 도구 자체를 막는 등급(보기 · 고치기 · 전부)은 '전부' 로 풀어 모드가 결정하게 한다."""
    if 모드 not in 모드목록:
        raise ValueError(f"모드는 {', '.join(모드목록)} 중 하나여야 합니다.")
    값 = dict(안전파일.json읽기(등급파일, {}, dict) or {})
    값["모드"] = 모드
    값["등급"] = "전부"
    안전파일.json쓰기(등급파일, 값)
    return 모드


def 쓸수있나(나물이름: str, 역할: str = "") -> tuple[bool, str]:
    """(허용 여부, 막혔을 때 알려줄 말). 역할이 있으면(일꾼 방) 그 역할 등급까지만."""
    지금 = 등급읽기()
    if 나물이름 in 역할더.get(역할, ()):
        역할 = ""                                # 이 나물은 역할이 따로 허락한다 — 전체 등급만 본다
    if 역할 in 역할등급 and _순번(역할등급[역할]) < _순번(지금):
        지금 = 역할등급[역할]
    필요 = 나물등급.get(나물이름)
    if 필요 is None:
        return True, ""      # 모르는 이름은 서버가 따로 처리한다
    if _순번(지금) >= _순번(필요):
        return True, ""
    return False, (
        f"지금은 '{지금}' 등급이라 막혀 있습니다. "
        f"이걸 쓰려면 '{필요}' 이상이어야 합니다. "
        f"사용자에게 등급을 올려 달라고 말하고 멈추세요."
    )


def 지금쓸수있는것() -> list:
    지금 = 등급읽기()
    return sorted(
        이름 for 이름, 필요 in 나물등급.items() if _순번(지금) >= _순번(필요)
    )
